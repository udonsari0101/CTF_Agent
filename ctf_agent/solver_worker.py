def _bounded_utf8(value: str, maximum: int) -> str:
    encoded = value.encode("utf-8", errors="replace")
    if len(encoded) <= maximum:
        return value
    marker = "…"
    marker_size = len(marker.encode("utf-8"))
    if maximum < marker_size:
        return encoded[:maximum].decode("utf-8", errors="ignore")
    prefix = encoded[: maximum - marker_size].decode("utf-8", errors="ignore").rstrip()
    return prefix + marker


def _safe_activity_text(value: object, maximum: int = MAX_LIVE_COMMAND_BYTES) -> str | None:
    """Keep a useful command/query preview while removing common credentials."""

    if not isinstance(value, str):
        return None
    text = value.replace("\r\n", "\n").replace("\r", "\n").strip()
    if not text:
        return None
    text = _WRITEUP_INSTRUCTION_CONTROL.sub(" ", text)
    text = _ACTIVITY_SECRET.sub(lambda match: match.group(1) + "[redacted]", text)
    text = re.sub(
        r"(?i)\b(https?://)([^/@\s:]+):([^/@\s]+)@",
        r"\1[redacted]@",
        text,
    )
    text = re.sub(
        r"-----BEGIN [^-\r\n]*PRIVATE KEY-----[\s\S]*?-----END [^-\r\n]*PRIVATE KEY-----",
        "[redacted private key]",
        text,
        flags=re.IGNORECASE,
    )
    return _bounded_utf8(text, maximum)



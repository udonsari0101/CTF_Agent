    def _account_digest(self, value: object) -> bytes | None:
        """Return a process-keyed digest without retaining an account id."""

        if not _valid_token(value):
            return None
        return hashlib.blake2s(
            value.encode("utf-8"),
            key=self._account_match_key,
        ).digest()

    def _remember_chatgpt_account(self, value: object) -> None:
        self._expected_chatgpt_account_digest = self._account_digest(value)

    def _refresh_account_match(self, params: object) -> bool | None:
        """Reduce refresh identity metadata to a non-identifying tri-state."""

        if not isinstance(params, Mapping) or params.get("reason") != "unauthorized":
            return None
        previous = self._account_digest(params.get("previousAccountId"))
        expected = self._expected_chatgpt_account_digest
        if previous is None or expected is None:
            return None
        return secrets.compare_digest(previous, expected)

    def _record_refresh_account_match(self, params: object) -> bool | None:
        value = params.get("accountMatch") if isinstance(params, Mapping) else None
        match = value if isinstance(value, bool) else None
        if match is False or self._last_refresh_account_match is None:
            self._last_refresh_account_match = match
        return match


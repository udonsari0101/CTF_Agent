@dataclass(slots=True)
class ClaudeFileCredential:
    """Opaque Claude credential bytes after the exchange copy is unlinked."""

    raw: bytearray = field(repr=False)

    def install(self, config_dir: Path) -> Path:
        config_dir.mkdir(parents=True, mode=0o700, exist_ok=False)
        if os.name == "posix":
            config_dir.chmod(0o700)
        target = config_dir / ".credentials.json"
        descriptor = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            with os.fdopen(descriptor, "wb", closefd=False) as stream:
                stream.write(self.raw)
                stream.flush()
                os.fsync(stream.fileno())
        finally:
            os.close(descriptor)
        _fsync_directory(config_dir)
        return target

    def erase(self) -> None:
        for index in range(len(self.raw)):
            self.raw[index] = 0
        self.raw.clear()


def _consume_staged_bytes(active: Path, expected_sha256: str, filename: str) -> bytearray:
    """Read one no-follow auth file, unlink it, fsync, then parse in memory."""

    if filename not in {"auth.json", ".credentials.json"}:
        raise WorkerRefusal("invalid_auth_stage", "임시 인증 파일 이름을 확인할 수 없습니다.")
    target = active / filename
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
    descriptor = None
    raw = bytearray()
    try:
        descriptor = os.open(target, flags)
        info = os.fstat(descriptor)
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size < 2 or info.st_size > MAX_AUTH_BYTES:
            raise WorkerRefusal("invalid_auth_stage", "임시 인증 파일 형식을 확인할 수 없습니다.")
        if os.name == "posix" and (info.st_mode & 0o077):
            raise WorkerRefusal("invalid_auth_permissions", "임시 인증 파일 권한이 안전하지 않습니다.")
        while True:
            chunk = os.read(descriptor, min(65_536, MAX_AUTH_BYTES + 1 - len(raw)))
            if not chunk:
                break
            raw.extend(chunk)
            if len(raw) > MAX_AUTH_BYTES:
                raise WorkerRefusal("invalid_auth_stage", "임시 인증 파일이 너무 큽니다.")
    except FileNotFoundError as exc:
        raise WorkerRefusal(
            "credential_required",
            "worker 재시작 후 선택 계정 인증정보를 다시 준비해야 합니다.",
            category="auth",
            retryable=True,
        ) from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)

    # Remove the only exchange copy before parsing or spawning the provider. The
    # directory fsync makes the deletion durable across a worker/container crash.
    target.unlink(missing_ok=False)
    _fsync_directory(active)
    try:
        if not secrets_compare(hashlib.sha256(raw).hexdigest(), expected_sha256):
            raise WorkerRefusal("auth_integrity_failed", "임시 인증 파일 무결성 확인에 실패했습니다.", category="auth")
        return raw
    except BaseException:
        for index in range(len(raw)):
            raw[index] = 0
        raise


def consume_staged_credential(active: Path, expected_sha256: str) -> MemoryCredential:
    raw = _consume_staged_bytes(active, expected_sha256, "auth.json")
    try:
        value = _strict_json(bytes(raw), "invalid_auth_stage")
        if set(value) - {"auth_mode", "OPENAI_API_KEY", "tokens", "last_refresh"}:
            raise WorkerRefusal("invalid_auth_stage", "지원하지 않는 Codex 인증 형식입니다.", category="auth")
        key, tokens = value.get("OPENAI_API_KEY"), value.get("tokens")
        if isinstance(key, str) and _valid_token(key) and tokens is None:
            return MemoryCredential({"type": "apiKey", "apiKey": key})
        if isinstance(tokens, dict) and _valid_token(tokens.get("access_token")) and _valid_token(tokens.get("account_id")) and key is None:
            # chatgptAuthTokens is explicitly memory-only in the pinned app-server
            # protocol.  A missing account_id cannot be safely guessed.
            login = {
                "type": "chatgptAuthTokens",
                "accessToken": tokens["access_token"],
                "chatgptAccountId": tokens["account_id"],
            }
            plan_type = _chatgpt_plan_type(tokens)
            if plan_type is not None:
                login["chatgptPlanType"] = plan_type
            return MemoryCredential(login)
        raise WorkerRefusal(
            "external_auth_unsupported",
            "이 Codex 인증 파일은 메모리 전용 실행 인증으로 변환할 수 없습니다.",
            category="auth",
        )
    finally:
        for index in range(len(raw)):
            raw[index] = 0


def consume_staged_claude_credential(active: Path, expected_sha256: str) -> ClaudeFileCredential:
    raw = _consume_staged_bytes(active, expected_sha256, ".credentials.json")
    try:
        # Claude owns this schema.  Validate only that the opaque file remains
        # a bounded, duplicate-free JSON object before installing it in the
        # private provider home.
        _strict_json(bytes(raw), "invalid_auth_stage")
        return ClaudeFileCredential(raw)
    except BaseException:
        for index in range(len(raw)):
            raw[index] = 0
        raise


def discard_credential_before_runtime_attestation(exchange: Path) -> bool:
    """Remove a credential left by an interrupted worker without reading it.

    A restarted container must run its fixed command-sandbox canary before it
    creates any model thread.  Leaving an old active/auth.json in place during
    that command would invalidate the very visibility property being tested.
    The web coordinator retains the owned source credential and restages it
    only after this new worker publishes a fresh successful attestation.
    """

    removed = False
    for name in ("auth.json", ".credentials.json"):
        target = exchange / "active" / name
        try:
            info = target.lstat()
        except FileNotFoundError:
            continue
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise WorkerRefusal("invalid_auth_stage", "재시작 후 남은 인증 파일 형식을 확인할 수 없습니다.")
        target.unlink()
        removed = True
    if removed:
        _fsync_directory(exchange / "active")
    return removed


def _remove_input_canary_tree(path: Path, exchange: Path) -> None:
    """Remove only a trusted canary directory immediately below exchange."""

    if not re.fullmatch(r"\.input-canary-[A-Za-z0-9_-]{6,64}", path.name):
        raise WorkerRefusal("input_canary_cleanup_failed", "solver 입력 검증 경로를 안전하게 정리할 수 없습니다.")
    try:
        if path.is_symlink() or path.resolve().parent != exchange.resolve():
            raise WorkerRefusal("input_canary_cleanup_failed", "solver 입력 검증 경로를 안전하게 정리할 수 없습니다.")

        def remove_readonly(operation, target, failure):
            if os.name != "nt":
                raise failure
            details = os.lstat(target)
            os.chmod(
                target,
                0o700 if stat.S_ISDIR(details.st_mode) else 0o600,
                follow_symlinks=False,
            )
            operation(target)

        shutil.rmtree(path, onexc=remove_readonly)
        _fsync_directory(exchange)
    except WorkerRefusal:
        raise
    except OSError as exc:
        raise WorkerRefusal(
            "input_canary_cleanup_failed",
            "solver 입력 검증 경로를 안전하게 정리할 수 없습니다.",
        ) from exc


def discard_input_canaries_before_runtime_attestation(exchange: Path) -> None:
    """Clean crash-left read-only-input canaries before inventory attestation."""

    for path in exchange.glob(".input-canary-*"):
        _remove_input_canary_tree(path, exchange)


def assert_runtime_exchange_inventory(exchange: Path) -> None:
    """Refuse to execute even a canary beside an unknown staged artifact."""

    allowed = {"active", "runtime", "worker.json", "worker.lock"}
    try:
        entries = list(exchange.iterdir())
    except OSError as exc:
        raise WorkerRefusal("invalid_exchange_inventory", "solver 교환 디렉터리를 확인할 수 없습니다.") from exc
    if any(entry.name not in allowed for entry in entries):
        raise WorkerRefusal(
            "invalid_exchange_inventory",
            "정리되지 않은 solver 임시 파일이 있어 실행을 거부했습니다.",
        )
    active = exchange / "active"
    if active.exists() and (active.is_symlink() or not active.is_dir() or active.resolve().parent != exchange.resolve()):
        raise WorkerRefusal("invalid_exchange_inventory", "solver 활성 디렉터리를 확인할 수 없습니다.")
    if any((active / name).exists() for name in ("auth.json", ".credentials.json")):
        raise WorkerRefusal("auth_cleanup_failed", "자체 점검 전에 인증 파일을 제거하지 못했습니다.", category="auth")


def assert_scratch_root_clean(root: Path) -> None:
    if root.is_symlink() or not root.is_dir():
        raise WorkerRefusal("scratch_isolation_failed", "solver 임시 작업공간을 확인할 수 없습니다.")
    try:
        entries = list(root.iterdir())
    except OSError as exc:
        raise WorkerRefusal("scratch_isolation_failed", "solver 임시 작업공간을 확인할 수 없습니다.") from exc
    if entries:
        raise WorkerRefusal("scratch_cleanup_failed", "이전 solver 작업의 임시 파일이 남아 다음 작업을 차단했습니다.")


def _scratch_entry_owned(details: os.stat_result, current_uid: int | None) -> bool:
    """Return whether mode changes are permitted for a scratch entry."""

    return current_uid is None or details.st_uid == current_uid


def recover_crash_scratch(root: Path) -> None:
    """Remove only crash-left scratch trees after the PID namespace is clean."""

    current_uid = os.geteuid() if hasattr(os, "geteuid") else None

    def invalid(code: str = "scratch_cleanup_failed") -> WorkerRefusal:
        message = (
            "solver 임시 작업 경로를 확인할 수 없습니다."
            if code == "scratch_isolation_failed"
            else "이전 solver 임시 작업을 안전하게 정리할 수 없습니다."
        )
        return WorkerRefusal(code, message)

    if os.name == "posix":
        flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0)
        try:
            root_fd = os.open(root, flags)
        except OSError as exc:
            raise invalid("scratch_isolation_failed") from exc
        try:
            details = os.fstat(root_fd)
            if (
                not stat.S_ISDIR(details.st_mode)
                or (current_uid is not None and details.st_uid != current_uid)
                or bool(details.st_mode & stat.S_IWOTH)
            ):
                raise invalid("scratch_isolation_failed")
            os.fchmod(root_fd, 0o700)
            names = os.listdir(root_fd)

            def remove_contents(directory_fd: int) -> None:
                for name in os.listdir(directory_fd):
                    try:
                        child = os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
                    except OSError as exc:
                        raise invalid() from exc
                    if stat.S_ISDIR(child.st_mode) and not stat.S_ISLNK(child.st_mode):
                        try:
                            # NAS/WebDAV indexers may add a writable ``._DAV``
                            # directory owned by the host while a job is
                            # running.  The unprivileged worker cannot chmod
                            # that directory, but can still safely traverse
                            # and remove it through the already-open parent.
                            # Only change modes on entries owned by this
                            # worker; the operations below remain the
                            # authoritative accessibility check for foreign
                            # entries.
                            if _scratch_entry_owned(child, current_uid):
                                os.chmod(
                                    name,
                                    0o700,
                                    dir_fd=directory_fd,
                                    follow_symlinks=False,
                                )
                            child_fd = os.open(name, flags, dir_fd=directory_fd)
                        except OSError as exc:
                            raise invalid() from exc
                        try:
                            opened = os.fstat(child_fd)
                            if _scratch_entry_owned(opened, current_uid):
                                os.fchmod(child_fd, 0o700)
                            remove_contents(child_fd)
                        finally:
                            os.close(child_fd)
                        try:
                            os.rmdir(name, dir_fd=directory_fd)
                        except OSError as exc:
                            raise invalid() from exc
                    else:
                        # Unlink symlinks, sockets, FIFOs, device nodes and
                        # hard-linked regular files without opening or following.
                        try:
                            os.unlink(name, dir_fd=directory_fd)
                        except OSError as exc:
                            raise invalid() from exc

            for name in names:
                if not re.fullmatch(r"ctf-(?:job|attest)-[A-Za-z0-9_-]{6,64}", name):
                    raise WorkerRefusal(
                        "scratch_cleanup_failed",
                        "알 수 없는 solver 임시 파일이 남아 있습니다.",
                    )
                try:
                    top = os.stat(name, dir_fd=root_fd, follow_symlinks=False)
                except OSError as exc:
                    raise invalid() from exc
                if (
                    not stat.S_ISDIR(top.st_mode)
                    or stat.S_ISLNK(top.st_mode)
                    or (current_uid is not None and top.st_uid != current_uid)
                ):
                    raise invalid()
                try:
                    os.chmod(
                        name,
                        0o700,
                        dir_fd=root_fd,
                        follow_symlinks=False,
                    )
                    tree_fd = os.open(name, flags, dir_fd=root_fd)
                except OSError as exc:
                    raise invalid() from exc
                try:
                    os.fchmod(tree_fd, 0o700)
                    remove_contents(tree_fd)
                finally:
                    os.close(tree_fd)
                try:
                    os.rmdir(name, dir_fd=root_fd)
                except OSError as exc:
                    raise invalid() from exc
            if names:
                os.fsync(root_fd)
        finally:
            os.close(root_fd)
        return

    # Development fallback for Windows, where dir_fd operations are absent.
    try:
        details = root.lstat()
        if not stat.S_ISDIR(details.st_mode) or stat.S_ISLNK(details.st_mode):
            raise invalid("scratch_isolation_failed")
        root_resolved = root.resolve(strict=True)
        entries = list(root.iterdir())
        for entry in entries:
            if not re.fullmatch(r"ctf-(?:job|attest)-[A-Za-z0-9_-]{6,64}", entry.name):
                raise WorkerRefusal(
                    "scratch_cleanup_failed",
                    "알 수 없는 solver 임시 파일이 남아 있습니다.",
                )
            entry_details = entry.lstat()
            if (
                entry.is_symlink()
                or not stat.S_ISDIR(entry_details.st_mode)
                or entry.resolve(strict=True).parent != root_resolved
            ):
                raise invalid()
        for entry in entries:
            shutil.rmtree(entry)
        if entries:
            _fsync_directory(root)
    except WorkerRefusal:
        raise
    except OSError as exc:
        raise invalid() from exc


def secrets_compare(left: str, right: str) -> bool:
    return hashlib.sha256(left.encode()).digest() == hashlib.sha256(right.encode()).digest()


def _valid_token(value: object) -> bool:
    return isinstance(value, str) and 0 < len(value) <= 131_072 and not any(ord(char) < 33 for char in value)


def _jwt_payload(value: object) -> Mapping[str, Any] | None:
    """Decode bounded JWT claims for metadata only; backend auth still verifies the token."""

    if not _valid_token(value):
        return None
    parts = value.split(".")
    if len(parts) != 3 or not parts[1]:
        return None
    try:
        encoded = parts[1].encode("ascii")
        raw = base64.b64decode(encoded + b"=" * (-len(encoded) % 4), altchars=b"-_", validate=True)
        if len(raw) > MAX_AUTH_BYTES:
            return None
        payload = json.loads(raw.decode("utf-8"), parse_constant=lambda _: (_ for _ in ()).throw(ValueError()))
    except (ValueError, TypeError, UnicodeError, binascii.Error):
        return None
    return payload if isinstance(payload, Mapping) else None


def _chatgpt_plan_type(tokens: Mapping[str, Any]) -> str | None:
    """Read the official ChatGPT plan claim without retaining other JWT data."""

    # Codex derives external-auth metadata from the access token.  The id token
    # fallback preserves the same value from a regular managed auth.json when
    # that access-token claim is unavailable.
    for name in ("access_token", "id_token"):
        payload = _jwt_payload(tokens.get(name))
        auth = payload.get("https://api.openai.com/auth") if payload is not None else None
        plan = auth.get("chatgpt_plan_type") if isinstance(auth, Mapping) else None
        if isinstance(plan, str) and re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", plan):
            return plan
    return None


def _strict_json(raw: bytes, code: str) -> dict[str, Any]:
    def pairs(items):
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError("duplicate key")
            result[key] = value
        return result

    try:
        value = json.loads(raw.decode("utf-8"), object_pairs_hook=pairs, parse_constant=lambda _: (_ for _ in ()).throw(ValueError()))
        if not isinstance(value, dict):
            raise ValueError("object required")
        return value
    except (ValueError, UnicodeError, TypeError, RecursionError) as exc:
        raise WorkerRefusal(code, "작업 제어 파일 형식을 확인할 수 없습니다.") from exc


def _read_json(path: Path, maximum: int = MAX_CONTROL_BYTES) -> dict[str, Any]:
    descriptor = None
    try:
        descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
        info = os.fstat(descriptor)
        if not stat.S_ISREG(info.st_mode) or info.st_size > maximum:
            raise WorkerRefusal("invalid_control_file", "작업 제어 파일 형식을 확인할 수 없습니다.")
        raw = b""
        while len(raw) <= maximum:
            chunk = os.read(descriptor, min(65_536, maximum + 1 - len(raw)))
            if not chunk:
                break
            raw += chunk
        if len(raw) > maximum:
            raise WorkerRefusal("invalid_control_file", "작업 제어 파일이 너무 큽니다.")
        return _strict_json(raw, "invalid_control_file")
    except FileNotFoundError as exc:
        raise WorkerRefusal("missing_control_file", "작업 제어 파일을 찾을 수 없습니다.", retryable=True) from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)


def _read_solver_text(path: Path, maximum: int, *, private: bool = False) -> str | None:
    """Read one model-written regular file without following an escape link."""

    descriptor = None
    try:
        descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise WorkerRefusal("invalid_solver_output", "solver 결과 파일 형식을 확인할 수 없습니다.", stage="solve") from exc
    try:
        info = os.fstat(descriptor)
        if (
            not stat.S_ISREG(info.st_mode)
            or info.st_nlink != 1
            or info.st_size > maximum
            or (private and os.name == "posix" and info.st_mode & 0o077)
        ):
            raise WorkerRefusal("invalid_solver_output", "solver 결과 파일 형식을 확인할 수 없습니다.", stage="solve")
        raw = bytearray()
        while len(raw) <= maximum:
            chunk = os.read(descriptor, min(65_536, maximum + 1 - len(raw)))
            if not chunk:
                break
            raw.extend(chunk)
        if len(raw) > maximum:
            raise WorkerRefusal("invalid_solver_output", "solver 결과 파일이 너무 큽니다.", stage="solve")
        try:
            return raw.decode("utf-8", errors="strict")
        except UnicodeError as exc:
            raise WorkerRefusal("invalid_solver_output", "solver 결과 파일 인코딩을 확인할 수 없습니다.", stage="solve") from exc
    finally:
        os.close(descriptor)


def _capture_solver_artifact(path: Path) -> SolverArtifact | None:
    """Snapshot one bounded regular solver file without following links."""

    descriptor = None
    try:
        descriptor = os.open(
            path,
            os.O_RDONLY
            | getattr(os, "O_BINARY", 0)
            | getattr(os, "O_NOFOLLOW", 0),
        )
    except OSError:
        return None
    try:
        before = os.fstat(descriptor)
        if (
            not stat.S_ISREG(before.st_mode)
            or before.st_nlink != 1
            or not 1 <= before.st_size <= MAX_CHECKPOINT_SOLVER_BYTES
        ):
            return None
        content = bytearray()
        while len(content) <= MAX_CHECKPOINT_SOLVER_BYTES:
            chunk = os.read(
                descriptor,
                min(65_536, MAX_CHECKPOINT_SOLVER_BYTES + 1 - len(content)),
            )
            if not chunk:
                break
            content.extend(chunk)
        after = os.fstat(descriptor)
        if (
            len(content) != before.st_size
            or len(content) > MAX_CHECKPOINT_SOLVER_BYTES
            or after.st_ino != before.st_ino
            or after.st_size != before.st_size
            or after.st_mtime_ns != before.st_mtime_ns
        ):
            return None
        return solver_artifact_from_bytes(bytes(content))
    except (OSError, ValueError):
        return None
    finally:
        os.close(descriptor)


def _canonical_solver_artifact_payload(value: object) -> dict[str, Any] | None:
    try:
        return parse_solver_artifact(value).payload() if value is not None else None
    except (TypeError, ValueError):
        return None


def _restore_solver_artifact(workdir: Path, artifact: SolverArtifact) -> Path:
    """Restore a validated immutable snapshot into a fresh job workspace."""

    try:
        artifact = parse_solver_artifact(artifact.payload())
    except (AttributeError, TypeError, ValueError) as exc:
        raise WorkerRefusal(
            "invalid_retry_checkpoint",
            "이전 solver.py를 안전하게 복원할 수 없습니다.",
            category="safety",
            stage="solve",
        ) from exc
    destination = workdir / "solver.py"
    if destination.exists() or destination.is_symlink():
        raise WorkerRefusal(
            "invalid_retry_checkpoint",
            "이전 solver.py를 안전하게 복원할 수 없습니다.",
            category="safety",
            stage="solve",
        )
    temporary = workdir / f".solver-restore-{secrets.token_hex(12)}.tmp"
    descriptor = None
    try:
        descriptor = os.open(
            temporary,
            os.O_WRONLY
            | os.O_CREAT
            | os.O_EXCL
            | getattr(os, "O_BINARY", 0)
            | getattr(os, "O_NOFOLLOW", 0),
            0o600,
        )
        remaining = memoryview(artifact.content)
        while remaining:
            written = os.write(descriptor, remaining)
            if written <= 0:
                raise OSError("short solver artifact write")
            remaining = remaining[written:]
        os.fsync(descriptor)
        details = os.fstat(descriptor)
        if (
            not stat.S_ISREG(details.st_mode)
            or details.st_nlink != 1
            or details.st_size != len(artifact.content)
        ):
            raise OSError("invalid restored solver artifact")
        os.close(descriptor)
        descriptor = None
        os.replace(temporary, destination)
        _fsync_directory(workdir)
        restored = _capture_solver_artifact(destination)
        if restored is None or not secrets.compare_digest(restored.sha256, artifact.sha256):
            raise OSError("restored solver artifact digest mismatch")
        return destination
    except OSError as exc:
        raise WorkerRefusal(
            "invalid_retry_checkpoint",
            "이전 solver.py를 안전하게 복원할 수 없습니다.",
            category="safety",
            stage="solve",
        ) from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)
        temporary.unlink(missing_ok=True)


def _solver_notes(workdir: Path, maximum: int = 1_000_000) -> str:
    """Collect the original ANALYSIS/VULN/NEXT handoff for the write-up turn."""

    sections: list[str] = []
    remaining = maximum
    for name in ("ANALYSIS.md", "VULN.md", "NEXT.md"):
        text = _read_solver_text(workdir / "notes" / name, remaining)
        if text is None:
            continue
        text = text.replace("\r\n", "\n").replace("\r", "\n").strip()
        if _CONTROL.search(text):
            raise WorkerRefusal("invalid_solver_output", "solver 분석 노트 형식을 확인할 수 없습니다.", stage="solve")
        section = f"## {name}\n\n{text}" if text else f"## {name}"
        if len(section) > remaining:
            raise WorkerRefusal("invalid_solver_output", "solver 분석 노트가 너무 큽니다.", stage="solve")
        sections.append(section)
        remaining -= len(section) + 2
    return "\n\n".join(sections)


def _validated_flag_candidate(path: Path) -> str | None:
    """Read and validate the private handoff written by ``submit-flag``."""

    candidate = _read_solver_text(path, 4000, private=True)
    if candidate is None:
        return None
    candidate = candidate.strip()
    if (
        not candidate
        or len(candidate) > 4000
        or "\n" in candidate
        or "\r" in candidate
        or _CONTROL.search(candidate)
    ):
        raise WorkerRefusal(
            "invalid_flag_candidate",
            "submit-flag 결과를 확인할 수 없습니다.",
            stage="solve",
        )
    return candidate


def _validated_remote_request(path: Path) -> str | None:
    """Read the one-shot request created by ``request-remote``."""

    note = _read_solver_text(path, MAX_REQUEST_BYTES, private=True)
    if note is None:
        return None
    note = note.strip()
    if (
        not note
        or len(note.encode("utf-8")) > MAX_REQUEST_BYTES
        or any(not character.isprintable() for character in note)
    ):
        raise WorkerRefusal(
            "invalid_remote_request",
            "request-remote 요청을 확인할 수 없습니다.",
            stage="solve",
        )
    return note


def _max_reasoning_requested(workdir: Path) -> bool:
    """Accept only the agent's explicit, standalone MAX_REQUIRED handoff."""

    note = _read_solver_text(
        workdir / "notes" / "NEXT.md", MAX_CHECKPOINT_NOTES_BYTES
    )
    if note is None:
        return False
    return any(line.strip() == "MAX_REQUIRED" for line in note.splitlines())


def _consume_max_reasoning_request(workdir: Path) -> bool:
    """Atomically remove only standalone MAX_REQUIRED lines from NEXT.md."""

    notes = workdir / "notes"
    try:
        if (
            notes.is_symlink()
            or not notes.is_dir()
            or notes.resolve() != workdir.resolve() / "notes"
        ):
            raise WorkerRefusal(
                "invalid_solver_output",
                "solver 노트 경로 형식을 확인할 수 없습니다.",
                stage="solve",
            )
    except OSError as exc:
        raise WorkerRefusal(
            "invalid_solver_output",
            "solver 노트 경로 형식을 확인할 수 없습니다.",
            stage="solve",
        ) from exc
    path = notes / "NEXT.md"
    note = _read_solver_text(path, MAX_CHECKPOINT_NOTES_BYTES)
    if note is None or not any(
        line.strip() == "MAX_REQUIRED" for line in note.splitlines()
    ):
        return False
    retained = [
        line for line in note.splitlines() if line.strip() != "MAX_REQUIRED"
    ]
    normalized = "\n".join(retained).rstrip("\n") + "\n"
    temporary = path.with_name(f".{path.name}.{os.getpid()}.{time.time_ns()}.tmp")
    try:
        descriptor = os.open(
            temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600
        )
        try:
            with os.fdopen(descriptor, "wb", closefd=False) as stream:
                stream.write(normalized.encode("utf-8"))
                stream.flush()
                os.fsync(stream.fileno())
        finally:
            os.close(descriptor)
        os.replace(temporary, path)
        _fsync_directory(path.parent)
    finally:
        temporary.unlink(missing_ok=True)
    return True


async def _watch_remote_request(
    path: Path,
    requested: asyncio.Event,
    cancelled: asyncio.Event,
    result: dict[str, Any],
) -> None:
    while not cancelled.is_set():
        try:
            note = _validated_remote_request(path)
        except WorkerRefusal as exc:
            result["error"] = exc
            requested.set()
            cancelled.set()
            return
        if note is not None:
            result["note"] = note
            requested.set()
            cancelled.set()
            return
        await asyncio.sleep(FLAG_WATCH_INTERVAL_SECONDS)


async def _watch_flag_candidate(
    path: Path,
    publish: Callable[[str], object],
    interrupt: Callable[[str], Awaitable[None]] | None = None,
) -> None:
    """Publish each atomically replaced candidate and stop its Codex turn."""

    last_candidate: str | None = None
    while True:
        candidate = _validated_flag_candidate(path)
        if candidate is not None and candidate != last_candidate:
            accepted = publish(candidate)
            last_candidate = candidate
            if accepted is not False and interrupt is not None:
                await interrupt(candidate)
        await asyncio.sleep(FLAG_WATCH_INTERVAL_SECONDS)


async def _run_with_flag_watcher(
    operation: Awaitable[dict[str, str]],
    candidate_path: Path,
    publish: Callable[[str], object],
    interrupt: Callable[[str], Awaitable[None]] | None = None,
) -> dict[str, str]:
    """Run discovery and its flag watcher as one cancellation-safe operation."""

    last_published: str | None = None
    accepted_candidate: str | None = None

    def publish_once(candidate: str) -> object:
        nonlocal accepted_candidate, last_published
        # The original coordinator keeps one candidate pending until a human
        # rejects it.  Once this isolated solve has durably handed one off, no
        # later model-written replacement may emit another hook or interrupt.
        if accepted_candidate is not None:
            return False
        if candidate == last_published:
            return False
        accepted = publish(candidate)
        last_published = candidate
        if accepted is not False:
            accepted_candidate = candidate
        return accepted

    def pin_accepted_candidate(result: dict[str, str]) -> dict[str, str]:
        # Discovery and the candidate file can finish/change in either order.
        # The first accepted handoff is the job-authoritative value.
        candidate = _validated_flag_candidate(candidate_path)
        if candidate is not None:
            publish_once(candidate)
        if accepted_candidate is None or result.get("flag") == accepted_candidate:
            return result
        return {**result, "flag": accepted_candidate}

    discovery_task = asyncio.ensure_future(operation)
    watcher_task = asyncio.create_task(
        _watch_flag_candidate(candidate_path, publish_once, interrupt)
    )
    try:
        done, _ = await asyncio.wait(
            (discovery_task, watcher_task),
            return_when=asyncio.FIRST_COMPLETED,
        )
        if discovery_task in done:
            try:
                result = await discovery_task
            except AppServerFailure:
                # A provider terminal event can beat the 25 ms watcher tick.
                # Final-scan the fsynced handoff before allowing that event to
                # turn an already discovered flag into a failed solve.
                candidate = _validated_flag_candidate(candidate_path)
                if candidate is not None:
                    publish_once(candidate)
                if accepted_candidate is not None:
                    return {"flag": accepted_candidate, "private_notes": ""}
                raise
            return pin_accepted_candidate(result)
        if watcher_task in done:
            # The watcher is intentionally unbounded; completion means its
            # validation failed and discovery must not continue.
            await watcher_task
            raise WorkerRefusal(
                "flag_watcher_stopped",
                "submit-flag 감시가 예기치 않게 중단되었습니다.",
                stage="solve",
            )
        raise WorkerRefusal(
            "flag_watcher_stopped",
            "submit-flag 감시 상태를 확인할 수 없습니다.",
            stage="solve",
        )
    finally:
        if not discovery_task.done():
            discovery_task.cancel()
        await asyncio.gather(discovery_task, return_exceptions=True)
        # Close the tiny race between the last polling tick and turn exit. This
        # is also reached when a deadline or provider error cancels discovery.
        candidate = _validated_flag_candidate(candidate_path)
        if candidate is not None:
            publish_once(candidate)
        watcher_task.cancel()
        await asyncio.gather(watcher_task, return_exceptions=True)


def _write_json(path: Path, payload: Mapping[str, Any], *, mode: int = 0o600) -> None:
    temporary = path.with_name(f".{path.name}.{os.getpid()}.{time.time_ns()}.tmp")
    data = json.dumps(payload, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode("utf-8")
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    try:
        with os.fdopen(descriptor, "wb", closefd=False) as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
    finally:
        os.close(descriptor)
    os.replace(temporary, path)
    _fsync_directory(path.parent)


def _fsync_directory(path: Path) -> None:
    if os.name != "posix":
        return
    descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def harden_current_process() -> None:
    """Deny core dumps and same-uid ptrace/proc inspection where Linux supports it."""

    if resource is not None:
        try:
            resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
        except (OSError, ValueError):
            pass
    if sys.platform.startswith("linux"):
        # PR_SET_DUMPABLE=4.  Failure means the runtime cannot make the memory
        # credential boundary claimed by the adapter.
        if ctypes.CDLL(None, use_errno=True).prctl(4, 0, 0, 0, 0) != 0:
            errno = ctypes.get_errno()
            raise WorkerRefusal("process_hardening_failed", f"프로세스 메모리 보호를 설정하지 못했습니다 ({errno}).")
        # PR_SET_CHILD_SUBREAPER=36 keeps double-forked model processes under
        # the worker so they can be reaped before another credential is staged.
        if ctypes.CDLL(None, use_errno=True).prctl(36, 1, 0, 0, 0) != 0:
            errno = ctypes.get_errno()
            raise WorkerRefusal("process_hardening_failed", f"하위 프로세스 회수 보호를 설정하지 못했습니다 ({errno}).")


@dataclass(frozen=True, slots=True)
class PlatformAttestation:
    ready: bool
    checks: dict[str, bool]
    reason: str | None = None

    def public(self) -> dict[str, Any]:
        return {
            "protocol": EXCHANGE_PROTOCOL,
            "ready": self.ready,
            "checks": dict(self.checks),
            "reason": self.reason,
            "checked_at": time.time(),
        }


def trusted_inet_sockets_available() -> bool:
    """Prove that the trusted worker profile can create IPv4 provider/DNS sockets."""

    for kind in (socket.SOCK_STREAM, socket.SOCK_DGRAM):
        try:
            value = socket.socket(socket.AF_INET, kind)
        except OSError:
            return False
        else:
            value.close()
    return True


def inspect_platform(
    exchange: Path,
    *,
    input_root: Path = SOLVER_INPUT_ROOT,
    mountinfo: str | None = None,
    status: str | None = None,
    apparmor_status: str | None = None,
    allow_apparmor_only: bool | None = None,
    external_sandbox: bool | None = None,
    nproc_limit: int | None = None,
    trusted_inet_sockets: bool | None = None,
) -> PlatformAttestation:
    """Verify the Compose boundary from inside the worker container."""

    checks = {
        "linux": sys.platform.startswith("linux"),
        "non_root": not hasattr(os, "geteuid") or os.geteuid() != 0,
        "exchange_exact": str(exchange.resolve()) == "/solver-exchange",
        # The immutable image may contain empty conventional directories.  The
        # isolation boundary is that neither persistent volume (nor any of its
        # descendants) is mounted into the solver container.
        "data_absent": True,
        "database_absent": True,
        "root_read_only": False,
        "exchange_mounted_rw": False,
        "runtime_mounted_ro": False,
        "input_exact": str(Path(input_root).resolve()) == "/solver-input",
        "input_mounted_ro": False,
        "input_same_exchange": False,
        "scratch_exact": str(SCRATCH_ROOT.resolve()) == "/solver-scratch",
        "scratch_directory": False,
        "scratch_not_symlink": False,
        "scratch_owned": False,
        "scratch_not_world_writable": False,
        "scratch_mounted_rw": False,
        "capabilities_dropped": False,
        "no_new_privileges": False,
        "seccomp_filter": False,
        "apparmor_enforced": False,
        "external_sandbox": False,
        "trusted_inet_sockets": False,
        "security_boundary": False,
        "private_pid_namespace": os.getpid() == 1,
    }
    mountinfo_readable = mountinfo is not None
    if mountinfo is None:
        try:
            mountinfo = Path("/proc/self/mountinfo").read_text(encoding="utf-8", errors="strict")
            mountinfo_readable = True
        except OSError:
            mountinfo = ""
    checks["data_absent"] = mountinfo_readable
    checks["database_absent"] = mountinfo_readable
    for line in mountinfo.splitlines():
        fields = line.split()
        if len(fields) < 6:
            continue
        mountpoint = fields[4].replace("\\040", " ")
        options = set(fields[5].split(","))
        if mountpoint == "/":
            checks["root_read_only"] = "ro" in options
        if mountpoint == "/solver-exchange":
            checks["exchange_mounted_rw"] = "rw" in options
        if mountpoint == "/solver-exchange/runtime":
            checks["runtime_mounted_ro"] = "ro" in options
        if mountpoint == "/solver-input":
            checks["input_mounted_ro"] = "ro" in options
        if mountpoint == "/solver-scratch":
            checks["scratch_mounted_rw"] = "rw" in options
        if mountpoint == "/data" or mountpoint.startswith("/data/"):
            checks["data_absent"] = False
        if mountpoint == "/database" or mountpoint.startswith("/database/"):
            checks["database_absent"] = False
    try:
        checks["input_same_exchange"] = os.path.samefile(exchange, input_root)
    except OSError:
        checks["input_same_exchange"] = False
    try:
        scratch_stat = SCRATCH_ROOT.lstat()
        checks["scratch_directory"] = stat.S_ISDIR(scratch_stat.st_mode)
        checks["scratch_not_symlink"] = not stat.S_ISLNK(scratch_stat.st_mode)
        checks["scratch_owned"] = (
            not hasattr(os, "geteuid") or scratch_stat.st_uid == os.geteuid()
        )
        checks["scratch_not_world_writable"] = not bool(
            scratch_stat.st_mode & stat.S_IWOTH
        )
    except OSError:
        pass
    if status is None:
        try:
            status = Path("/proc/self/status").read_text(encoding="ascii", errors="strict")
        except OSError:
            status = ""
    values = {}
    for line in status.splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            values[key] = value.strip().split()[0] if value.strip() else ""
    checks["capabilities_dropped"] = values.get("CapEff") == "0000000000000000"
    checks["no_new_privileges"] = values.get("NoNewPrivs") == "1"
    checks["seccomp_filter"] = values.get("Seccomp") == "2"
    if apparmor_status is None:
        try:
            apparmor_status = Path("/proc/self/attr/current").read_text(encoding="ascii", errors="strict")
        except OSError:
            apparmor_status = ""
    checks["apparmor_enforced"] = apparmor_status.strip() == "ctf-agent-solver (enforce)"
    if allow_apparmor_only is None:
        allow_apparmor_only = os.environ.get("CTF_SOLVER_ALLOW_APPARMOR_ONLY") == "true"
    if external_sandbox is None:
        external_sandbox = os.environ.get("CTF_SOLVER_EXTERNAL_SANDBOX") == "true"
    checks["external_sandbox"] = bool(external_sandbox)
    if trusted_inet_sockets is None:
        trusted_inet_sockets = trusted_inet_sockets_available()
    checks["trusted_inet_sockets"] = bool(trusted_inet_sockets)
    external_boundary = bool(
        external_sandbox
        and allow_apparmor_only
        and checks["apparmor_enforced"]
        and checks["capabilities_dropped"]
        and checks["no_new_privileges"]
    )
    checks["security_boundary"] = checks["seccomp_filter"] or external_boundary
    informational = {"seccomp_filter", "apparmor_enforced", "external_sandbox"}
    missing = [name for name, passed in checks.items() if name not in informational and not passed]
    return PlatformAttestation(not missing, checks, None if not missing else ",".join(missing))



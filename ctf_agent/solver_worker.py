def codex_error_kind(payload: object) -> tuple[str | None, int | None]:
    """Read only the bounded app-server error discriminator and HTTP status."""

    info = payload.get("codexErrorInfo") if isinstance(payload, Mapping) else None
    if isinstance(info, str) and info in _CODEX_SCALAR_ERROR_KINDS:
        return info, None
    if isinstance(info, Mapping) and len(info) == 1:
        kind, details = next(iter(info.items()))
        if kind not in _CODEX_HTTP_ERROR_KINDS:
            return None, None
        status = details.get("httpStatusCode") if isinstance(details, Mapping) else None
        if not isinstance(status, int) or isinstance(status, bool) or not 100 <= status <= 599:
            status = None
        return kind, status
    return None, None


def safe_codex_failure(payload: object) -> dict[str, Any]:
    """Discard provider prose and retain only reviewed Codex error fields."""

    result: dict[str, Any] = {}
    if isinstance(payload, Mapping) and payload.get("code") in _SAFE_CODEX_WORKER_FAILURE_CODES:
        result["code"] = payload["code"]
    info = payload.get("codexErrorInfo") if isinstance(payload, Mapping) else None
    kind, status = codex_error_kind(payload)
    if kind in _CODEX_SCALAR_ERROR_KINDS and isinstance(info, str):
        result["codexErrorInfo"] = kind
    elif kind in _CODEX_HTTP_ERROR_KINDS:
        result["codexErrorInfo"] = {kind: {"httpStatusCode": status}}
    if not result:
        result["code"] = "provider_error"
    return result


def provider_retry_progress(
    payload: object,
    *,
    model: str | None = None,
    authenticated_preflight: bool = False,
) -> str:
    """Map retry notifications to fixed UI-safe progress codes."""

    kind, status = codex_error_kind(payload)
    if status == 403 or (
        authenticated_preflight
        and model in {"gpt-daybreak-blue-latest", "gpt-daybreak-red-latest"}
        and (kind in {"unauthorized", "badRequest"} or status == 400)
    ):
        return "provider_access_check"
    if kind == "unauthorized" or status == 401:
        return "provider_auth_retry"
    if kind in {"usageLimitExceeded", "sessionBudgetExceeded"}:
        return "provider_quota_retry"
    if kind == "rateLimitExceeded" or status == 429:
        return "provider_rate_limit_retry"
    if kind in {"serverOverloaded", "internalServerError"} or status in {500, 502, 503, 504}:
        return "provider_overloaded_retry"
    if kind in {
        "httpConnectionFailed",
        "responseStreamConnectionFailed",
        "responseStreamDisconnected",
        "responseTooManyFailedAttempts",
    }:
        return "provider_connection_retry"
    return "provider_retrying"


def provider_retry_is_terminal(payload: object) -> bool:
    """Identify retry labels that cannot recover inside this isolated job."""

    kind, status = codex_error_kind(payload)
    return kind in {
        "unauthorized",
        "usageLimitExceeded",
        "sessionBudgetExceeded",
        "contextWindowExceeded",
        "cyberPolicy",
        "misalignmentPolicyViolation",
        "badRequest",
    } or status in {400, 401, 403}


def safe_rate_limit_snapshot(value: object) -> dict[str, Any] | None:
    """Reduce one app-server quota snapshot to reviewed scalar fields."""

    if not isinstance(value, Mapping):
        return None
    candidate: dict[str, Any] = {}
    for source, target in (("limitId", "limit_id"), ("limitName", "limit_name")):
        if isinstance(value.get(source), str):
            candidate[target] = value[source]
    reached = value.get("rateLimitReachedType")
    if isinstance(reached, str) and reached:
        candidate["reached_type"] = reached if reached in {
            "rate_limit_reached",
            "workspace_owner_credits_depleted",
            "workspace_member_credits_depleted",
            "workspace_owner_usage_limit_reached",
            "workspace_member_usage_limit_reached",
        } else "rate_limit_reached"
    if isinstance(value.get("spendControlReached"), bool):
        candidate["spend_control_reached"] = value["spendControlReached"]
    windows = []
    for kind in ("primary", "secondary"):
        source = value.get(kind)
        if not isinstance(source, Mapping):
            continue
        window: dict[str, Any] = {"kind": kind}
        for source_key, target_key in (
            ("windowDurationMins", "window_minutes"),
            ("usedPercent", "used_percent"),
            ("resetsAt", "resets_at"),
        ):
            if isinstance(source.get(source_key), int) and not isinstance(source[source_key], bool):
                window[target_key] = source[source_key]
        windows.append(window)
    if windows:
        candidate["windows"] = windows
    return normalize_rate_limit_context(candidate)


def safe_rate_limit_response(value: object) -> dict[str, Any] | None:
    """Select the documented legacy bucket from a full quota read."""

    if not isinstance(value, Mapping):
        return None
    direct = safe_rate_limit_snapshot(value.get("rateLimits"))
    if direct:
        return direct
    buckets = value.get("rateLimitsByLimitId")
    if not isinstance(buckets, Mapping):
        return None
    preferred = safe_rate_limit_snapshot(buckets.get("codex"))
    if preferred:
        return preferred
    for bucket in buckets.values():
        normalized = safe_rate_limit_snapshot(bucket)
        if normalized:
            return normalized
    return None


def merge_rate_limit_context(current: object, update: object) -> dict[str, Any] | None:
    """Merge a documented sparse rolling update into the last full read."""

    current = normalize_rate_limit_context(current)
    update = normalize_rate_limit_context(update)
    if update is None:
        return current
    if current is None or (
        current.get("limit_id")
        and update.get("limit_id")
        and current["limit_id"] != update["limit_id"]
    ):
        return update
    merged = dict(current)
    for key in ("limit_id", "limit_name", "reached_type", "spend_control_reached"):
        if key in update:
            merged[key] = update[key]
    windows = {item["kind"]: dict(item) for item in current.get("windows", [])}
    for item in update.get("windows", []):
        windows[item["kind"]] = {**windows.get(item["kind"], {}), **item}
    if windows:
        merged["windows"] = [windows[kind] for kind in ("primary", "secondary") if kind in windows]
    return normalize_rate_limit_context(merged)


def failure_with_rate_limit(payload: object, rate_limit: object) -> dict[str, Any]:
    """Attach quota to a provider error after dropping all free-form fields."""

    result = safe_codex_failure(payload)
    normalized = normalize_rate_limit_context(rate_limit)
    if normalized:
        result["rate_limit"] = normalized
    return result


def safe_app_server_failure_code(payload: object) -> str:
    """Return only an allowlisted protocol code for startup diagnostics."""

    value = payload.get("code") if isinstance(payload, Mapping) else None
    if isinstance(value, int) and not isinstance(value, bool) and -99999 <= value <= 99999:
        return str(value)
    if isinstance(value, str) and re.fullmatch(r"[A-Za-z0-9_-]{1,64}", value):
        return value.lower()
    return "unknown"


def sanitize_startup_stderr(value: bytes) -> str | None:
    """Bound and redact diagnostics emitted before any credential is staged."""

    text = value.decode("utf-8", errors="replace")
    text = re.sub(r"https?://\S+", "<url>", text, flags=re.IGNORECASE)
    text = re.sub(r"(?<![A-Za-z0-9])/(?:[^\s:'\"/]+/)*[^\s:'\"/]+", "<path>", text)
    text = re.sub(r"\b[A-Za-z0-9_+/=-]{32,}\b", "<redacted>", text)
    text = re.sub(r"[^\x20-\x7e]+", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:400] if text else None


def resolve_codex_command(exchange: Path, version: str, expected_digest: str | None = None) -> list[str]:
    """Resolve only an image binary or an atomically published runtime copy."""

    if not isinstance(version, str) or not _VERSION.fullmatch(version):
        raise WorkerRefusal("invalid_runtime_version", "Codex 실행 버전을 확인할 수 없습니다.")
    if version == REQUIRED_CODEX_VERSION and expected_digest is None:
        executable = shutil.which("codex")
        if executable:
            if os.environ.get("CTF_SOLVER_EXTERNAL_SANDBOX") == "true":
                native = _native_codex_binary(Path("/usr/local/lib/node_modules/@openai/codex"))
                if native:
                    return [str(native)]
                raise WorkerRefusal("invalid_runtime", "이미지에 포함된 Codex native runtime을 확인할 수 없습니다.")
            return [executable]
    runtime = exchange / "runtime" / f"codex-{version}"
    if runtime.exists():
        if runtime.is_symlink() or runtime.resolve().parent != (exchange / "runtime").resolve():
            raise WorkerRefusal("invalid_runtime_path", "Codex runtime 경로를 확인할 수 없습니다.")
        _validate_runtime_tree(runtime)
        if not isinstance(expected_digest, str) or not re.fullmatch(r"[0-9a-f]{64}", expected_digest):
            raise WorkerRefusal("invalid_runtime", "게시된 Codex runtime 무결성 값이 없습니다.")
        if not secrets_compare(runtime_tree_digest(runtime), expected_digest):
            raise WorkerRefusal("runtime_integrity_failed", "게시된 Codex runtime 무결성 확인에 실패했습니다.")
        package = _read_json(runtime / "node_modules" / "@openai" / "codex" / "package.json")
        script = runtime / "node_modules" / "@openai" / "codex" / "bin" / "codex.js"
        node = shutil.which("node")
        if package.get("version") != version or not node or not script.is_file() or script.is_symlink():
            raise WorkerRefusal("invalid_runtime", "게시된 Codex runtime을 확인할 수 없습니다.")
        if os.environ.get("CTF_SOLVER_EXTERNAL_SANDBOX") == "true":
            native = _native_codex_binary(runtime / "node_modules" / "@openai" / "codex")
            if native:
                return [str(native)]
            raise WorkerRefusal("invalid_runtime", "게시된 Codex native runtime을 확인할 수 없습니다.")
        return [node, str(script)]
    raise WorkerRefusal("codex_runtime_unavailable", "선택한 Codex runtime이 worker에 게시되지 않았습니다.")


def resolve_claude_command(exchange: Path, version: str, expected_digest: str | None = None) -> list[str]:
    """Use the pinned image binary or an immutable published Claude binary."""
    if not isinstance(version, str) or not _VERSION.fullmatch(version):
        raise WorkerRefusal("invalid_runtime_version", "Claude 실행 버전이 잘못되었습니다.")
    if version == REQUIRED_CLAUDE_VERSION and expected_digest is None:
        executable = shutil.which("claude")
        if executable:
            return [executable]
    root = exchange / "runtime"
    runtime = root / f"claude-{version}"
    if runtime.is_symlink() or not runtime.is_dir() or runtime.resolve().parent != root.resolve():
        raise WorkerRefusal("claude_runtime_unavailable", "선택한 Claude Code가 worker에 게시되지 않았습니다.")
    if not isinstance(expected_digest, str) or not re.fullmatch(r"[0-9a-f]{64}", expected_digest):
        raise WorkerRefusal("invalid_runtime", "Claude runtime 무결성 값이 없습니다.")
    if not secrets_compare(runtime_tree_digest(runtime), expected_digest):
        raise WorkerRefusal("runtime_integrity_failed", "Claude runtime 무결성 확인에 실패했습니다.")
    architecture = {"x86_64": "x64", "amd64": "x64", "aarch64": "arm64", "arm64": "arm64"}.get(platform.machine().lower())
    if not architecture:
        raise WorkerRefusal("invalid_runtime", "지원하지 않는 Claude runtime 아키텍처입니다.")
    package = _read_json(runtime / "node_modules" / "@anthropic-ai" / "claude-code" / "package.json")
    executable = runtime / "node_modules" / "@anthropic-ai" / f"claude-code-linux-{architecture}" / "claude"
    if package.get("version") != version or not executable.is_file() or executable.is_symlink():
        raise WorkerRefusal("invalid_runtime", "Claude Code 패키지 버전을 확인하지 못했습니다.")
    return [str(executable)]


def _validate_runtime_tree(root: Path) -> None:
    count = 0
    for current, directories, files in os.walk(root, followlinks=False):
        current_path = Path(current)
        if not current_path.resolve().is_relative_to(root.resolve()):
            raise WorkerRefusal("invalid_runtime", "Codex runtime 경로가 게시 영역 밖을 가리킵니다.")
        for name in directories + files:
            count += 1
            if count > 100_000:
                raise WorkerRefusal("invalid_runtime", "Codex runtime 파일 수가 허용 범위를 넘었습니다.")
            details = (current_path / name).lstat()
            if stat.S_ISLNK(details.st_mode) or (name in files and not stat.S_ISREG(details.st_mode)):
                raise WorkerRefusal("invalid_runtime", "Codex runtime에 링크 또는 특수 파일이 있습니다.")


def runtime_tree_digest(root: Path) -> str:
    """Hash a validated immutable runtime by relative path and file bytes."""

    _validate_runtime_tree(root)
    digest = hashlib.sha256()
    files = sorted((path for path in root.rglob("*") if path.is_file()),
                   key=lambda path: path.relative_to(root).as_posix())
    for path in files:
        relative = path.relative_to(root).as_posix().encode("utf-8")
        digest.update(len(relative).to_bytes(8, "big"))
        digest.update(relative)
        descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
        try:
            details = os.fstat(descriptor)
            if not stat.S_ISREG(details.st_mode) or details.st_nlink != 1:
                raise WorkerRefusal("invalid_runtime", "Codex runtime 파일 형식을 확인할 수 없습니다.")
            while chunk := os.read(descriptor, 4 * 1024 * 1024):
                digest.update(chunk)
        finally:
            os.close(descriptor)
    return digest.hexdigest()



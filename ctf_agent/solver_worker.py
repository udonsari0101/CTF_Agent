"""Isolated single-job worker for the filesystem solver exchange.

The worker is intended to run in a separate, hardened container.  It never
opens the web database or data mounts.  A web-side coordinator atomically
places exactly one job at ``/solver-exchange/active`` and consumes the ordered
JSON events written here.

Credential handling has no stdout-event race: the staged auth file is read and
unlinked before Codex is started.  Authentication is then installed through
the app-server memory-login RPC before any thread or model turn exists.  If the
pinned Codex version does not support that RPC, the job is refused; there is no
fallback that leaves auth.json visible to model tools.
"""


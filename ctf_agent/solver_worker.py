def _install_refinement_project_manual(workdir: Path, locale: str = "ko") -> None:
    """Replace only ephemeral provider manuals with the fixed editorial rules."""

    manual = (_ENGLISH_REFINEMENT_SYSTEM_PROMPT + "\nUse exactly the six section headings: "
              + ", ".join(_ENGLISH_WRITEUP_SECTIONS) + ".\n") if locale == "en" else _WRITEUP_REFINEMENT_PROJECT_MANUAL
    encoded = manual.encode("utf-8")
    for name in ("AGENTS.md", "CLAUDE.md"):
        path = workdir / name
        if path.is_symlink() or not path.is_file():
            raise WorkerRefusal(
                "invalid_writeup_refinement_context",
                "write-up 보완 작업의 고정 편집 지침을 준비하지 못했습니다.",
                category="safety",
                stage="writeup",
            )
        try:
            path.chmod(0o600)
            with path.open("wb") as stream:
                stream.write(encoded)
                stream.flush()
                os.fsync(stream.fileno())
            path.chmod(0o400)
        except OSError as exc:
            raise WorkerRefusal(
                "invalid_writeup_refinement_context",
                "write-up 보완 작업의 고정 편집 지침을 준비하지 못했습니다.",
                category="safety",
                stage="writeup",
            ) from exc


def _read_refinement_source(active: Path, expected_digest: str) -> str:
    path = active / "writeup-source.md"
    descriptor = None
    try:
        descriptor = os.open(
            path,
            os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0),
        )
        details = os.fstat(descriptor)
        if (
            not stat.S_ISREG(details.st_mode)
            or details.st_nlink != 1
            or not 1 <= details.st_size <= MAX_OUTPUT_TEXT
        ):
            raise OSError("invalid source write-up")
        raw = bytearray()
        while len(raw) <= MAX_OUTPUT_TEXT:
            chunk = os.read(descriptor, min(65_536, MAX_OUTPUT_TEXT + 1 - len(raw)))
            if not chunk:
                break
            raw.extend(chunk)
        after = os.fstat(descriptor)
        if (
            len(raw) != details.st_size
            or len(raw) > MAX_OUTPUT_TEXT
            or after.st_ino != details.st_ino
            or after.st_size != details.st_size
            or after.st_mtime_ns != details.st_mtime_ns
            or not secrets.compare_digest(hashlib.sha256(raw).hexdigest(), expected_digest)
        ):
            raise OSError("source write-up changed")
        text = raw.decode("utf-8", errors="strict")
        if not text or _CONTROL.search(text):
            raise ValueError("invalid source write-up text")
        return text
    except (OSError, UnicodeError, ValueError) as exc:
        raise WorkerRefusal(
            "invalid_writeup_refinement_context",
            "보완할 write-up 원본을 안전하게 확인할 수 없습니다.",
            category="safety",
            stage="writeup",
        ) from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)


def _markdown_code_fence(source: str) -> str:
    longest = max((len(match.group(0)) for match in re.finditer(r"`+", source)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}python\n{source.rstrip()}\n{fence}"


def _include_solver_source(markdown: str, source: str) -> str:
    """Ensure the worker-verified solver.py is reproduced in the code section."""

    if not source or source.rstrip() in markdown:
        return markdown
    code_heading = re.search(r"(?m)^## 풀이 코드 및 명령어[ \t]*$", markdown)
    flag_heading = re.search(r"(?m)^## Flag[ \t]*$", markdown)
    if code_heading is None or flag_heading is None or flag_heading.start() <= code_heading.end():
        return markdown
    before = markdown[: flag_heading.start()].rstrip()
    after = markdown[flag_heading.start() :].lstrip()
    return f"{before}\n\n{_markdown_code_fence(source)}\n\n{after}"


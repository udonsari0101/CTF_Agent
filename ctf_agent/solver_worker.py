    async def _stderr_reader(self) -> None:
        """Drain stderr while retaining only fixed, non-sensitive categories."""

        if not self.process or not self.process.stderr:
            return
        patterns = (
            (b"read-only file system", "read_only_filesystem"),
            (b"permission denied", "permission_denied"),
            (b"operation not permitted", "operation_not_permitted"),
            (b"no such file or directory", "missing_file"),
            (b"unknown feature", "unknown_feature"),
            (b"unexpected argument", "unexpected_argument"),
            (b"unrecognized", "unrecognized_argument"),
            (b"invalid configuration", "invalid_configuration"),
            (b"failed to load", "load_failed"),
            (b"failed to create", "create_failed"),
            (b"landlock", "landlock"),
            (b"seccomp", "seccomp"),
            (b"panicked", "panic"),
        )
        while chunk := await self.process.stderr.read(4096):
            lowered = chunk.lower()
            matched = False
            for needle, category in patterns:
                if needle in lowered:
                    self.stderr_categories.add(category)
                    matched = True
            if not matched and lowered.strip():
                self.stderr_categories.add("other")
            if self.configuration is None and len(self.safe_startup_stderr or "") < 400:
                safe = sanitize_startup_stderr(chunk)
                if safe:
                    self.safe_startup_stderr = ((self.safe_startup_stderr or "") + " " + safe).strip()[:400]

    async def _reader(self) -> None:
        try:
            while line := await self.process.stdout.readline():
                if len(line) > MAX_RPC_LINE:
                    raise WorkerRefusal("provider_response_too_large", "Codex 응답이 허용 범위를 넘었습니다.")
                try:
                    message = json.loads(line)
                except (ValueError, UnicodeError):
                    continue
                if not isinstance(message, dict):
                    continue
                if "id" in message and "method" not in message:
                    future = self.pending.get(message["id"])
                    if future and not future.done():
                        future.set_result(message)
                elif "id" in message and "method" in message:
                    # An externally supplied access token cannot be refreshed
                    # inside the isolated worker because its refresh token is
                    # deliberately never staged.  Surface that fixed condition
                    # to the active turn after denying the request; otherwise
                    # app-server retries a 401 while the UI shows only a generic
                    # model heartbeat.  Every other server request remains
                    # denied, including approvals, elicitation and tools.
                    method = message.get("method")
                    refresh_required = method == "account/chatgptAuthTokens/refresh"
                    attestation_unavailable = method == "attestation/generate"
                    self.process.stdin.write(
                        (json.dumps({"id": message["id"], "error": {
                            "code": -32601,
                            "message": (
                                "External authentication refresh unavailable"
                                if refresh_required
                                else "Client attestation unavailable"
                                if attestation_unavailable
                                else "Denied by isolated worker"
                            ),
                        }}) + "\n").encode()
                    )
                    await self.process.stdin.drain()
                    if refresh_required:
                        self.notifications.put_nowait({
                            "method": "ctf/account-refresh-required",
                            "params": {
                                "accountMatch": self._refresh_account_match(
                                    message.get("params")
                                ),
                            },
                        })
                    elif attestation_unavailable:
                        # The service deliberately does not opt in to client
                        # attestation and cannot mint the opaque, host-owned
                        # token.  If a mismatched app-server requests one, keep
                        # only this fixed diagnostic and never retain params.
                        self.notifications.put_nowait({
                            "method": "ctf/attestation-unavailable",
                            "params": {},
                        })
                else:
                    if message.get("method") == "account/rateLimits/updated":
                        values = message.get("params")
                        update = safe_rate_limit_snapshot(values.get("rateLimits")) if isinstance(values, Mapping) else None
                        self.rate_limit_context = merge_rate_limit_context(self.rate_limit_context, update)
                    try:
                        self.notifications.put_nowait(message)
                    except asyncio.QueueFull:
                        raise WorkerRefusal("provider_event_overflow", "Codex 이벤트가 허용 범위를 넘었습니다.")
        except asyncio.CancelledError:
            self.reader_failure_code = "provider_stream_cancelled"
        except OSError:
            self.reader_failure_code = "provider_stream_failed"
        except Exception as exc:
            self.reader_failure_code = (
                exc.error.code
                if isinstance(exc, WorkerRefusal)
                else "provider_stream_failed"
            )
            for future in self.pending.values():
                if not future.done():
                    future.set_exception(exc)
        finally:
            for future in self.pending.values():
                if not future.done():
                    future.set_exception(AppServerFailure({"code": "provider_unavailable"}))
            self.reader_stopped.set()

    async def request(self, method: str, params: dict[str, Any] | None = None, *, timeout: int = 30) -> dict[str, Any]:
        if not self.process or self.process.returncode is not None:
            raise AppServerFailure({"code": "provider_unavailable"})
        self.sequence += 1
        request_id = self.sequence
        future = asyncio.get_running_loop().create_future()
        self.pending[request_id] = future
        try:
            request = {"id": request_id, "method": method}
            if params is not None:
                request["params"] = params
            self.process.stdin.write((json.dumps(request) + "\n").encode())
            await self.process.stdin.drain()
            message = await asyncio.wait_for(future, timeout)
            if "error" in message:
                raise AppServerFailure(message["error"])
            result = message.get("result")
            if not isinstance(result, dict):
                raise AppServerFailure({"code": "invalid_response"})
            return result
        finally:
            self.pending.pop(request_id, None)


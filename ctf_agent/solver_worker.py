class GuidanceMailbox:
    """Read owner-authored control files without exposing the exchange to tools."""

    def __init__(self, active: Path, job_id: str, writer: "EventWriter"):
        self.active = active
        self.job_id = job_id
        self.writer = writer
        self.directory = active / "guidance"
        self.inflight: set[str] = set()
        self.finished: set[str] = {
            event["guidance_id"]
            for event in _load_events(active, job_id)
            if event.get("kind") == "guidance"
            and isinstance(event.get("guidance_id"), str)
            and event.get("state") in {"delivered", "rejected"}
        }
        self._remove_finished_files()

    def _paths(self) -> list[Path]:
        if not self.directory.exists():
            return []
        if self.directory.is_symlink() or not self.directory.is_dir():
            raise WorkerRefusal(
                "invalid_guidance_path",
                "추가 명령 전달 경로를 확인할 수 없습니다.",
            )
        return sorted(self.directory.glob("[0-9a-f][0-9a-f]*.json"))

    def _remove_finished_files(self) -> None:
        for path in self._paths():
            if path.stem in self.finished:
                path.unlink(missing_ok=True)
        if self.directory.exists():
            _fsync_directory(self.directory)

    def _record(self, path: Path) -> GuidanceRecord:
        if not re.fullmatch(r"[0-9a-f]{32}\.json", path.name):
            raise WorkerRefusal(
                "invalid_guidance_file",
                "추가 명령 전달 파일을 확인할 수 없습니다.",
            )
        details = path.lstat()
        if not stat.S_ISREG(details.st_mode) or details.st_nlink != 1:
            raise WorkerRefusal(
                "invalid_guidance_file",
                "추가 명령 전달 파일을 확인할 수 없습니다.",
            )
        payload = _read_json(path, MAX_SOLVER_GUIDANCE_BYTES + 1024)
        if set(payload) not in ({
            "protocol", "job_id", "guidance_id", "message", "created_at",
        }, {
            "protocol", "job_id", "guidance_id", "message",
            "requested_delivery", "created_at",
        }):
            raise WorkerRefusal(
                "invalid_guidance_file",
                "추가 명령 전달 파일 형식을 확인할 수 없습니다.",
            )
        message = payload.get("message")
        created_at = payload.get("created_at")
        if (
            payload.get("protocol") != EXCHANGE_PROTOCOL
            or payload.get("job_id") != self.job_id
            or payload.get("guidance_id") != path.stem
            or not isinstance(message, str)
            or not message.strip()
            or message != message.replace("\r\n", "\n").replace("\r", "\n").strip()
            or _WRITEUP_INSTRUCTION_CONTROL.search(message)
            or len(message.encode("utf-8")) > MAX_SOLVER_GUIDANCE_BYTES
            or payload.get("requested_delivery", "same_turn") not in {"same_turn", "next_turn"}
            or not isinstance(created_at, (int, float))
            or isinstance(created_at, bool)
        ):
            raise WorkerRefusal(
                "invalid_guidance_file",
                "추가 명령 전달 파일 형식을 확인할 수 없습니다.",
            )
        return GuidanceRecord(path.stem, message, float(created_at), payload.get("requested_delivery", "same_turn"))

    def take_nowait_many(
        self,
        *,
        excluded: set[str] | None = None,
    ) -> list[GuidanceRecord]:
        skipped = excluded or set()
        result: list[GuidanceRecord] = []
        for path in self._paths():
            if path.stem in self.finished or path.stem in self.inflight or path.stem in skipped:
                continue
            record = self._record(path)
            self.inflight.add(record.guidance_id)
            result.append(record)
        return result

    def has_pending(self) -> bool:
        """Return whether a durable instruction still needs a provider turn."""

        return any(
            path.stem not in self.finished and path.stem not in self.inflight
            for path in self._paths()
        )

    async def next(
        self,
        cancelled: asyncio.Event,
        *,
        excluded: set[str] | None = None,
    ) -> GuidanceRecord:
        while not cancelled.is_set():
            records = self.take_nowait_many(excluded=excluded)
            if records:
                for extra in records[1:]:
                    self.inflight.discard(extra.guidance_id)
                return records[0]
            await asyncio.sleep(0.1)
        raise asyncio.CancelledError

    def release(self, record: GuidanceRecord) -> None:
        self.inflight.discard(record.guidance_id)

    def _finish(
        self,
        record: GuidanceRecord,
        *,
        state: str,
        provider_delivery: str | None,
        error_code: str | None,
    ) -> None:
        if record.guidance_id in self.finished:
            self.release(record)
            return
        self.writer.emit(
            "guidance",
            guidance_id=record.guidance_id,
            state=state,
            message=record.message,
            provider_delivery=provider_delivery,
            error_code=error_code,
        )
        self.finished.add(record.guidance_id)
        self.release(record)
        path = self.directory / f"{record.guidance_id}.json"
        path.unlink(missing_ok=True)
        if self.directory.exists():
            _fsync_directory(self.directory)

    def delivered(self, record: GuidanceRecord, provider_delivery: str) -> None:
        if provider_delivery not in {"same_turn", "next_turn"}:
            raise WorkerRefusal(
                "invalid_guidance_delivery",
                "추가 명령 전달 상태를 확인할 수 없습니다.",
            )
        self._finish(
            record,
            state="delivered",
            provider_delivery=provider_delivery,
            error_code=None,
        )

    def reject_all(self, error_code: str = "solve_finished") -> None:
        for record in self.take_nowait_many():
            self._finish(
                record,
                state="rejected",
                provider_delivery=None,
                error_code=error_code,
            )


class EventWriter:
    def __init__(self, active: Path, job_id: str):
        self.active = active
        self.job_id = job_id
        self.directory = active / "events"
        self.directory.mkdir(mode=0o700, exist_ok=True)
        existing = [int(path.stem) for path in self.directory.glob("[0-9]*.json") if path.stem.isdigit()]
        self.sequence = max(existing, default=0)

    def emit(self, kind: str, **payload: Any) -> dict[str, Any]:
        self.sequence += 1
        event = {
            "protocol": EXCHANGE_PROTOCOL,
            "job_id": self.job_id,
            "sequence": self.sequence,
            "kind": kind,
            "created_at": time.time(),
            **payload,
        }
        _write_json(self.directory / f"{self.sequence:08d}.json", event)
        return event

    def state(self, **payload: Any) -> None:
        _write_json(
            self.active / "state.json",
            {
                "protocol": EXCHANGE_PROTOCOL,
                "job_id": self.job_id,
                "last_sequence": self.sequence,
                "updated_at": time.time(),
                **payload,
            },
        )


def _visible_job_pids() -> list[int]:
    """Return every process in the worker's private PID namespace except self."""

    if not sys.platform.startswith("linux"):
        return []
    result = []
    for entry in Path("/proc").iterdir():
        if entry.name.isdigit():
            pid = int(entry.name)
            if pid != os.getpid():
                result.append(pid)
    return sorted(result)


def assert_clean_process_namespace() -> None:
    if not sys.platform.startswith("linux") or os.getpid() != 1:
        raise WorkerRefusal("pid_isolation_unavailable", "worker 전용 PID namespace를 확인할 수 없습니다.")
    residual = _visible_job_pids()
    if residual:
        raise WorkerRefusal("residual_processes", "이전 작업 프로세스가 남아 있어 새 인증정보를 열지 않았습니다.")


async def terminate_job_processes(primary_pid: int | None = None, *, timeout: float = 8.0) -> None:
    """Stop the app-server group and every escaped descendant before release.

    The worker must be PID 1 in a private namespace.  Consequently every other
    visible PID belongs to the current job; stopping all of them cannot touch
    the web service or host.  Processes are stopped before the final kill so a
    fork loop cannot continuously move the target set.  A stuck task keeps the
    slot blocked instead of allowing the next auth file to be staged.
    """

    if not sys.platform.startswith("linux") or os.getpid() != 1:
        raise WorkerRefusal("pid_isolation_unavailable", "worker 전용 PID namespace를 확인할 수 없습니다.")
    if primary_pid and primary_pid > 1:
        try:
            os.killpg(primary_pid, signal.SIGTERM)
        except (ProcessLookupError, PermissionError):
            pass
    deadline = time.monotonic() + timeout
    await asyncio.sleep(0)
    while time.monotonic() < deadline:
        pids = _visible_job_pids()
        if not pids:
            while True:
                try:
                    waited, _ = os.waitpid(-1, os.WNOHANG)
                    if waited == 0:
                        break
                except ChildProcessError:
                    break
            if not _visible_job_pids():
                return
        # Freeze every visible process, rescan to catch children forked just
        # before their parent stopped, then kill the stable set.
        for _ in range(4):
            for pid in pids:
                try:
                    os.kill(pid, signal.SIGSTOP)
                except ProcessLookupError:
                    pass
            expanded = sorted(set(pids) | set(_visible_job_pids()))
            if expanded == pids:
                break
            pids = expanded
        for pid in reversed(pids):
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        await asyncio.sleep(0.05)
        while True:
            try:
                waited, _ = os.waitpid(-1, os.WNOHANG)
                if waited == 0:
                    break
            except ChildProcessError:
                break
    raise WorkerRefusal("process_cleanup_failed", "작업 프로세스를 모두 종료하지 못해 다음 작업을 차단했습니다.")


class SolverWorker:
    def __init__(
        self,
        exchange: Path = Path("/solver-exchange"),
        *,
        driver_factory: Callable[[Path, Path, ModelConfiguration | None, str, str | None], CodexDriverProtocol] | None = None,
        platform_probe: Callable[[Path], PlatformAttestation] = inspect_platform,
        process_cleaner: Callable[[int | None], Awaitable[None]] = terminate_job_processes,
        process_assertion: Callable[[], None] = assert_clean_process_namespace,
        scratch_root: Path | None = None,
        input_root: Path | None = SOLVER_INPUT_ROOT,
    ):
        self.exchange = Path(exchange)
        self.driver_factory = driver_factory
        self.platform_probe = platform_probe
        self.process_cleaner = process_cleaner
        self.process_assertion = process_assertion
        self.scratch_root = Path(scratch_root) if scratch_root is not None else Path(
            os.environ.get("CTF_SOLVER_SCRATCH", str(SCRATCH_ROOT))
        )
        self.input_root = Path(input_root) if input_root is not None else None
        self.attestation: PlatformAttestation | None = None
        self.runtime_ready = False
        self.sandbox_attested = False
        self.provider_runtime_checks = {
            "codex_runtime_attested": False,
            "claude_runtime_attested": False,
            "toolchain_browser_functional": False,
            # strace remains installed and is exercised when the host permits
            # ptrace. Older Docker default seccomp profiles can deny ptrace
            # without weakening the AppArmor command boundary, so this is a
            # published capability diagnostic rather than a readiness gate.
            "toolchain_trace_functional": False,
        }
        self.clean = False
        self.instance_id = secrets.token_urlsafe(18)
        self.stopping = False
        self.current_task: asyncio.Task | None = None
        self.restart_required = False
        self.restart_reason: str | None = None
        self.startup_diagnostic: str | None = None

    def _new_driver(
        self,
        home: Path,
        challenge: Path,
        configuration: ModelConfiguration | None,
        version: str,
        runtime_digest: str | None = None,
    ) -> CodexDriverProtocol:
        if self.driver_factory:
            return self.driver_factory(home, challenge, configuration, version, runtime_digest)
        if configuration is not None and configuration.provider == "claude":
            command = resolve_claude_command(self.exchange, version, runtime_digest)
            return ClaudePrintDriver(
                home,
                challenge,
                configuration,
                command_prefix=command,
                expected_version=version,
            )
        command = resolve_codex_command(self.exchange, version, runtime_digest)
        return CodexAppServer(
            home,
            challenge,
            configuration,
            command_prefix=command,
            expected_version=version,
        )

    async def _verify_sandbox_canary(
        self,
        driver: CodexDriverProtocol,
        scratch: Path,
        challenge_source: Path,
    ) -> None:
        """Retry one transient command exit without weakening the canary."""

        try:
            await driver.sandbox_canary(
                os.getpid(), self.exchange, scratch, challenge_source
            )
        except WorkerRefusal as exc:
            if (
                exc.error.code != "sandbox_canary_failed"
                or tuple(exc.error.requirements) != ("command_exit",)
            ):
                raise
            await asyncio.sleep(0.2)
            await driver.sandbox_canary(
                os.getpid(), self.exchange, scratch, challenge_source
            )

    def _publish_worker(self, *, reason: str | None = None) -> None:
        base = self.attestation.public() if self.attestation else PlatformAttestation(False, {}, reason).public()
        base["checks"].update(self.provider_runtime_checks)
        base.update(
            {
                "ready": bool(
                    self.attestation
                    and self.attestation.ready
                    and self.runtime_ready
                    and self.sandbox_attested
                    and not self.restart_required
                ),
                "clean": self.clean,
                "sandbox_canary": self.sandbox_attested,
                "instance_id": self.instance_id,
                "pid": os.getpid(),
                "reason": reason or self.restart_reason or base.get("reason"),
                "diagnostic": self.startup_diagnostic,
            }
        )
        _write_json(self.exchange / "worker.json", base, mode=0o644)

    def _require_restart(self, reason: str) -> None:
        """Fail readiness and leave the long-lived loop after unsafe cleanup."""

        self.clean = False
        self.runtime_ready = False
        self.sandbox_attested = False
        self.restart_required = True
        self.restart_reason = reason
        self._publish_worker(reason=reason)

    def prepare(self) -> PlatformAttestation:
        self.exchange.mkdir(parents=True, exist_ok=True, mode=0o700)
        harden_current_process()
        self.attestation = self.platform_probe(self.exchange)
        if self.attestation.ready:
            try:
                self.process_assertion()
                recover_crash_scratch(self.scratch_root)
                assert_scratch_root_clean(self.scratch_root)
                self.clean = True
            except WorkerRefusal as exc:
                self.attestation = PlatformAttestation(False, self.attestation.checks, exc.error.code)
        self._publish_worker()
        return self.attestation

    async def attest_runtime(self) -> PlatformAttestation:
        """Prove the pinned CLI sandbox before advertising worker readiness."""

        for name in self.provider_runtime_checks:
            self.provider_runtime_checks[name] = False
        if not self.attestation or not self.attestation.ready:
            self._publish_worker()
            return self.attestation or PlatformAttestation(False, {}, "platform_not_attested")
        # A previous container may have stopped after the coordinator's atomic
        # stage but before consume_staged_credential.  Do not let even the
        # deterministic startup canary execute while that copy is visible.
        try:
            discard_credential_before_runtime_attestation(self.exchange)
            discard_input_canaries_before_runtime_attestation(self.exchange)
            assert_runtime_exchange_inventory(self.exchange)
        except WorkerRefusal as exc:
            self.runtime_ready = self.sandbox_attested = False
            self.attestation = PlatformAttestation(False, self.attestation.checks, exc.error.code)
            self._publish_worker(reason=exc.error.code)
            return self.attestation
        root = Path(tempfile.mkdtemp(prefix="ctf-attest-", dir=self.scratch_root))
        source, home = root / "source", root / "home"
        attachments = source / "attachments"
        archive_source = attachments / "0001_archive-canary.zip"
        driver = None
        failure = None
        attestation_stage = "workspace"
        try:
            source.mkdir(mode=0o700)
            attachments.mkdir(mode=0o700)
            with zipfile.ZipFile(archive_source, "w") as archive:
                archive.writestr("archive-canary.txt", b"archive sandbox ready\n")
            archive_source.chmod(0o400)
            attachments.chmod(0o500)
            source.chmod(0o500)
            preparation = asyncio.create_task(
                asyncio.to_thread(
                    prepare_agent_workspace,
                    root,
                    source,
                    challenge_name="Isolation canary",
                    challenge_text="Deterministic startup sandbox attestation.",
                    category="unknown",
                )
            )
            try:
                prepared = await asyncio.shield(preparation)
            except asyncio.CancelledError:
                # A cancelled to_thread future leaves its synchronous function
                # running.  Let the bounded archive child finish before the
                # finally block removes this scratch tree.
                await asyncio.gather(preparation, return_exceptions=True)
                raise
            archive_canary = prepared.workdir / "extracted/0001_archive-canary_extracted/archive-canary.txt"
            if (
                len(prepared.archive_report.expanded) != 1
                or not archive_canary.is_file()
                or archive_canary.read_bytes() != b"archive sandbox ready\n"
            ):
                raise WorkerRefusal(
                    "archive_sandbox_canary_failed",
                    "압축 해제 격리 자체 점검에 실패했습니다.",
                    requirements=("archive_child_isolated",),
                )
            scratch = prepared.workdir
            specifications = (
                ("codex", home, None, REQUIRED_CODEX_VERSION),
                (
                    "claude",
                    root / "claude-home",
                    ModelConfiguration("claude", "sonnet", "high", None),
                    REQUIRED_CLAUDE_VERSION,
                ),
            )
            for provider, provider_home, configuration, version in specifications:
                driver = self._new_driver(provider_home, scratch, configuration, version)
                try:
                    attestation_stage = provider + "_start"
                    await driver.start()
                    attestation_stage = provider + "_canary"
                    await self._verify_sandbox_canary(
                        driver, scratch, prepared.brief.parent
                    )
                    if provider == "codex":
                        sandbox_checks = getattr(driver, "sandbox_checks", {})
                        self.provider_runtime_checks["toolchain_trace_functional"] = bool(
                            isinstance(sandbox_checks, Mapping)
                            and sandbox_checks.get("toolchain_trace_functional") is True
                        )
                        self.provider_runtime_checks["toolchain_browser_functional"] = bool(
                            isinstance(sandbox_checks, Mapping)
                            and sandbox_checks.get("toolchain_browser_functional") is True
                        )
                    self.provider_runtime_checks[provider + "_runtime_attested"] = True
                finally:
                    try:
                        await asyncio.wait_for(driver.close(), timeout=DRIVER_CLOSE_TIMEOUT_SECONDS)
                    except Exception:
                        # The namespace-wide sweep immediately below is the
                        # authoritative boundary between provider canaries.
                        pass
                    await self.process_cleaner(getattr(driver, "pid", None))
                    self.process_assertion()
                    driver = None
            self.sandbox_attested = True
            self.runtime_ready = True
        except WorkerRefusal as exc:
            failure = exc.error.code
            if exc.error.requirements:
                failure += ":" + ",".join(exc.error.requirements)
            self.startup_diagnostic = getattr(driver, "safe_startup_stderr", None)
            self.runtime_ready = self.sandbox_attested = False
        except AppServerFailure as exc:
            protocol_code = safe_app_server_failure_code(exc.payload)
            child = getattr(driver, "process", None)
            if protocol_code == "provider_unavailable" and child is not None and child.returncode is None:
                try:
                    await asyncio.wait_for(child.wait(), timeout=0.5)
                except (asyncio.TimeoutError, OSError):
                    pass
            stderr_task = getattr(driver, "stderr_task", None)
            if stderr_task is not None and not stderr_task.done():
                try:
                    await asyncio.wait_for(asyncio.shield(stderr_task), timeout=0.5)
                except (asyncio.TimeoutError, OSError):
                    pass
            exit_code = getattr(child, "returncode", None)
            exit_detail = f":exit_{exit_code}" if isinstance(exit_code, int) and -255 <= exit_code <= 255 else ""
            stderr_categories = sorted(getattr(driver, "stderr_categories", ()))
            stderr_detail = ":stderr_" + "+".join(stderr_categories) if stderr_categories else ""
            self.startup_diagnostic = getattr(driver, "safe_startup_stderr", None)
            failure = f"app_server_{attestation_stage}_failed:{protocol_code}{exit_detail}{stderr_detail}"
            self.runtime_ready = self.sandbox_attested = False
        except Exception:
            failure = "sandbox_canary_failed"
            self.runtime_ready = self.sandbox_attested = False
        finally:
            if driver is not None:
                try:
                    await asyncio.wait_for(driver.close(), timeout=DRIVER_CLOSE_TIMEOUT_SECONDS)
                except Exception:
                    # Namespace cleanup below is authoritative. Provider
                    # shutdown may race after the process has already exited.
                    pass
            try:
                await self.process_cleaner(getattr(driver, "pid", None))
                self.process_assertion()
            except Exception:
                failure = "process_cleanup_failed"
                self.runtime_ready = self.sandbox_attested = self.clean = False
            else:
                try:
                    # Restore only the trusted canary source permissions so the
                    # authoritative scratch cleanup can remove the read-only
                    # input tree after the child boundary was checked.
                    try:
                        source.chmod(0o700)
                        attachments.chmod(0o700)
                        archive_source.chmod(0o600)
                    except OSError:
                        pass
                    self._remove_job_scratch(root)
                    assert_scratch_root_clean(self.scratch_root)
                    if not failure:
                        self.clean = True
                except Exception:
                    failure = "scratch_cleanup_failed"
                    self.runtime_ready = self.sandbox_attested = self.clean = False
        self._publish_worker(reason=failure)
        if failure:
            self.attestation = PlatformAttestation(False, self.attestation.checks, failure)
        return self.attestation

    async def process_active(self) -> bool:
        active = self.exchange / "active"
        if not active.exists():
            return False
        if active.is_symlink() or not active.is_dir() or active.resolve().parent != self.exchange.resolve():
            return False
        manifest = None
        writer = None
        guidance_mailbox = None
        driver = None
        credential = None
        cancel_event = asyncio.Event()
        cancel_watcher = None
        attachment_watcher = None
        remote_request_watcher = None
        remote_requested = asyncio.Event()
        remote_request_result: dict[str, Any] = {}
        deadline_expired = asyncio.Event()
        deadline_watcher = None
        home = None
        job_root = None
        scratch = None
        prior: dict[str, Any] = {}
        notes = ""
        solver_artifact_payload: dict[str, Any] | None = None
        release_status: str | None = None
        release_payload: dict[str, Any] = {}
        needs_credential = False
        try:
            manifest = JobManifest.load(active)
            writer = EventWriter(active, manifest.job_id)
            guidance_mailbox = GuidanceMailbox(active, manifest.job_id, writer)
            if manifest.deadline_unix is not None:
                deadline_watcher = asyncio.create_task(
                    _enforce_deadline(
                        manifest.deadline_unix,
                        deadline_expired,
                        cancel_event,
                        asyncio.current_task(),
                    )
                )
            self.clean = False
            self._publish_worker()
            prior = _load_optional_state(active, manifest.job_id)
            notes = prior.get("private_notes") if isinstance(prior.get("private_notes"), str) else ""
            solver_artifact_payload = _canonical_solver_artifact_payload(
                prior.get("solver_artifact")
            )
            if manifest.job_mode == "writeup_refine":
                if not notes:
                    notes = manifest.source_private_notes
                if solver_artifact_payload is None and manifest.source_solver_artifact is not None:
                    solver_artifact_payload = manifest.source_solver_artifact.payload()
            if prior.get("terminal") is True:
                # A crash may occur after the result state fsync and before the
                # clean-release marker.  A fresh PID namespace can safely finish
                # that release without rerunning the model.
                if any(event.get("kind") == "released" for event in _load_events(active, manifest.job_id)):
                    self.process_assertion()
                    self.clean = True
                    self._publish_worker()
                    return True
                release_status = str(prior.get("status") or "failed")
                release_payload = {
                    key: prior[key]
                    for key in ("flag", "writeup_markdown", "error")
                    if key in prior and prior[key] is not None
                }
                return True
            if not (
                self.attestation
                and self.attestation.ready
                and self.runtime_ready
                and self.sandbox_attested
            ):
                reason = (self.attestation.reason if self.attestation else None) or "runtime_not_attested"
                error = SolverError("isolation_unavailable", "solver 컨테이너 격리를 확인할 수 없습니다.", "worker", "safety", False,
                                    requirements=tuple(reason.split(",")))
                writer.emit("error", error=error.public(), terminal=False)
                writer.state(
                    status="releasing",
                    outcome="refused",
                    terminal=False,
                    error=error.public(),
                    solver_artifact=solver_artifact_payload,
                )
                release_status, release_payload = "refused", {"error": error.public()}
                return True

            if prior.get("status") in {"releasing", "cleanup_blocked"}:
                # The previous PID namespace preserved the completed outcome
                # before release, then either stopped or could not prove its own
                # cleanup.  A restarted container has now attested a clean
                # namespace and empty job scratch, so publish that durable outcome
                # without restaging credentials or rerunning a model turn.
                outcome = prior.get("outcome")
                if outcome not in {"completed", "cancelled", "failed", "refused", "flag_found", "needs_input"}:
                    raise WorkerRefusal("invalid_worker_state", "worker 정리 복구 상태를 확인할 수 없습니다.")
                self.process_assertion()
                assert_scratch_root_clean(self.scratch_root)
                release_status = outcome
                release_payload = {
                    key: prior[key]
                    for key in ("flag", "writeup_markdown", "error")
                    if key in prior and prior[key] is not None
                }
                return True

            _validate_challenge_tree(active / "challenge")
            if (active / "cancel").exists():
                writer.emit("cancelled", flag=prior.get("flag"), terminal=False)
                writer.state(
                    status="releasing", outcome="cancelled", terminal=False,
                    flag=prior.get("flag"), private_notes=bounded_checkpoint_notes(notes),
                    solver_artifact=solver_artifact_payload,
                )
                release_status = "cancelled"
                if prior.get("flag"):
                    release_payload["flag"] = prior["flag"]
                return True
            if (
                prior.get("status") == "awaiting_credential"
                and (active / "credential-request.json").is_file()
                and not (active / manifest.credential_file).exists()
            ):
                self.process_assertion()
                self.clean = True
                self._publish_worker(reason="awaiting_credential")
                return True
            # The coordinator may stage auth only after the previous job's
            # released event.  Rechecking here prevents opening it if a daemon
            # somehow survived that boundary.
            self.process_assertion()
            assert_scratch_root_clean(self.scratch_root)
            job_root = Path(tempfile.mkdtemp(prefix="ctf-job-", dir=self.scratch_root))
            home = job_root / "home"
            writer.emit("progress", code="inspecting_files")
            try:
                # Archive parsing runs in a disposable child while the owner
                # credential remains outside worker memory.  Offloading this
                # synchronous preparation also keeps worker heartbeats live
                # while the parent enforces the extractor wall timeout.
                preparation = asyncio.create_task(
                    asyncio.to_thread(
                        prepare_agent_workspace,
                        job_root,
                        active / "challenge",
                        challenge_name=manifest.challenge_name,
                        challenge_text=manifest.challenge_text,
                        related_context=manifest.related_context,
                        category=manifest.category,
                        flag_format=manifest.flag_format,
                        remote=manifest.remote,
                        remote_mode=manifest.remote_mode,
                        remote_access=manifest.network_enabled,
                        readonly_source_view=(
                            self.input_root / "active" / "challenge"
                            if self.input_root is not None
                            else None
                        ),
                    )
                )
                try:
                    prepared = await asyncio.shield(preparation)
                except asyncio.CancelledError:
                    # to_thread work cannot be force-cancelled. Wait for its
                    # bounded child/FS work before scratch cleanup so it cannot
                    # race by recreating files after rmtree.
                    await asyncio.gather(preparation, return_exceptions=True)
                    raise
                if manifest.job_mode == "writeup_refine":
                    _install_refinement_project_manual(prepared.workdir, manifest.writeup_locale)
            except ArchiveSafetyError as exc:
                raise WorkerRefusal(
                    exc.code,
                    exc.public_message,
                    stage="writeup" if manifest.job_mode == "writeup_refine" else "solve",
                    category="safety",
                ) from exc
            except (OSError, ValueError) as exc:
                raise WorkerRefusal(
                    "workspace_prepare_failed",
                    "원본 agent 작업공간을 안전하게 준비하지 못했습니다.",
                    stage="writeup" if manifest.job_mode == "writeup_refine" else "solve",
                ) from exc
            credential = (
                consume_staged_claude_credential(active, manifest.auth_sha256)
                if manifest.configuration.provider == "claude"
                else consume_staged_credential(active, manifest.auth_sha256)
            )
            (active / "credential-request.json").unlink(missing_ok=True)
            _fsync_directory(active)
            scratch = prepared.workdir
            if manifest.job_mode == "solve":
                attachment_watcher = asyncio.create_task(
                    _watch_live_attachments(
                        active / "challenge" / "attachments",
                        scratch / "attachments",
                        (
                            self.input_root / "active" / "challenge" / "attachments"
                            if self.input_root is not None else None
                        ),
                        writer,
                    )
                )
            if manifest.job_mode == "writeup_refine" and manifest.source_solver_artifact:
                _restore_solver_artifact(scratch, manifest.source_solver_artifact)
            elif manifest.retry_checkpoint and manifest.retry_checkpoint.solver_artifact:
                _restore_solver_artifact(
                    scratch,
                    manifest.retry_checkpoint.solver_artifact,
                )
            driver = self._new_driver(
                home,
                scratch,
                manifest.configuration,
                manifest.claude_version if manifest.configuration.provider == "claude" else manifest.codex_version,
                manifest.claude_runtime_sha256 if manifest.configuration.provider == "claude" else manifest.codex_runtime_sha256,
            )
            driver.guidance_mailbox = guidance_mailbox
            await driver.start()
            await self._verify_sandbox_canary(
                driver, scratch, prepared.brief.parent
            )
            await driver.login_memory(credential)
            credential.erase()
            credential = None
            # Repeat after login, when the access token exists only in protected
            # worker/app-server memory and any API-key auth file was removed.
            await self._verify_sandbox_canary(
                driver, scratch, prepared.brief.parent
            )
            cancel_watcher = asyncio.create_task(_watch_cancel(active / "cancel", cancel_event))

            async def progress(code: str, **details: str):
                if cancel_event.is_set():
                    raise asyncio.CancelledError
                writer.emit("progress", code=code, **details)

            async def activity(**details: Any):
                if cancel_event.is_set():
                    raise asyncio.CancelledError
                writer.emit("activity", **details)

            driver.activity_reporter = activity

            flag = prior.get("flag") if isinstance(prior.get("flag"), str) else None
            if manifest.job_mode == "writeup_refine":
                if flag is not None and flag != manifest.verified_flag:
                    raise WorkerRefusal(
                        "invalid_writeup_refinement_context",
                        "재개된 write-up 보완 작업의 Flag가 원본과 일치하지 않습니다.",
                        category="safety",
                        stage="writeup",
                    )
                flag = manifest.verified_flag
            if not flag:
                remote_request_watcher = asyncio.create_task(
                    _watch_remote_request(
                        scratch / ".remote-request",
                        remote_requested,
                        cancel_event,
                        remote_request_result,
                    )
                )
                writer.emit("status", status="running")
                writer.state(
                    status="running",
                    terminal=False,
                    private_notes=notes,
                    solver_artifact=solver_artifact_payload,
                )
                published_flag: str | None = None

                async def checkpoint_private_notes(value: str) -> None:
                    nonlocal notes, solver_artifact_payload
                    notes = bounded_checkpoint_notes(value)
                    current_artifact = _capture_solver_artifact(scratch / "solver.py")
                    if current_artifact is not None:
                        solver_artifact_payload = current_artifact.payload()
                    writer.state(
                        status="running",
                        terminal=False,
                        private_notes=notes,
                        solver_artifact=solver_artifact_payload,
                    )

                def publish_flag(candidate: str) -> bool:
                    nonlocal published_flag, notes, solver_artifact_payload
                    rejected = set(
                        manifest.retry_checkpoint.rejected_flags
                        if manifest.retry_checkpoint else ()
                    )
                    if candidate in rejected:
                        return False
                    if published_flag is not None:
                        return False
                    written_notes = _solver_notes(scratch)
                    if written_notes and not notes:
                        notes = bounded_checkpoint_notes(written_notes)
                    current_artifact = _capture_solver_artifact(scratch / "solver.py")
                    if current_artifact is not None:
                        solver_artifact_payload = current_artifact.payload()
                    writer.emit("flag", flag=candidate)
                    writer.state(
                        status="flag_found",
                        terminal=False,
                        flag=candidate,
                        private_notes=notes,
                        solver_artifact=solver_artifact_payload,
                    )
                    published_flag = candidate
                    return True

                discovery_operation = (
                    driver.run_discovery(
                        manifest,
                        scratch,
                        cancel_event,
                        progress,
                        checkpoint_private_notes,
                    )
                    if getattr(driver, "supports_checkpoints", False)
                    else driver.run_discovery(manifest, scratch, cancel_event, progress)
                )
                discovery = await _run_with_flag_watcher(
                    discovery_operation,
                    scratch / ".flag-candidate",
                    publish_flag,
                    (
                        driver.interrupt_after_flag
                        if not getattr(driver, "structured_discovery", True)
                        else None
                    ),
                )
                if (
                    getattr(driver, "effective_reasoning_effort", None) == "max"
                    and manifest.max_reasoning_available
                    and manifest.configuration.provider == "codex"
                    and manifest.configuration.reasoning_effort not in {"max", "ultra"}
                ):
                    manifest = replace(
                        manifest,
                        configuration=replace(
                            manifest.configuration, reasoning_effort="max"
                        ),
                    )
                # The command and turn completion can race by a few
                # milliseconds. Inspect once synchronously before stopping
                # the watcher so the handoff cannot be missed.
                if not remote_requested.is_set():
                    request_note = _validated_remote_request(scratch / ".remote-request")
                    if request_note is not None:
                        remote_request_result["note"] = request_note
                        remote_requested.set()
                        cancel_event.set()
                if remote_requested.is_set():
                    raise asyncio.CancelledError
                remote_request_watcher.cancel()
                await asyncio.gather(remote_request_watcher, return_exceptions=True)
                remote_request_watcher = None
                flag = published_flag or discovery["flag"]
                notes = discovery["private_notes"] or notes
                publish_flag(flag)
                current_artifact = _capture_solver_artifact(scratch / "solver.py")
                if current_artifact is not None:
                    solver_artifact_payload = current_artifact.payload()
                # State fsync occurs before the write-up turn, preserving the
                # notification order across a crash.
                writer.state(
                    status="flag_found",
                    terminal=False,
                    flag=flag,
                    private_notes=notes,
                    solver_artifact=solver_artifact_payload,
                )
            writer.emit("status", status="writing")
            writer.state(
                status="writing",
                terminal=False,
                flag=flag,
                private_notes=notes,
                solver_artifact=solver_artifact_payload,
            )
            markdown = await driver.run_writeup(manifest, scratch, flag, notes, cancel_event, progress)
            # Claude's print transport closes stdin for each response, so an
            # instruction submitted during that response cannot be injected
            # until the next turn.  Codex normally consumes guidance through
            # turn/steer; this loop is also its exact-turn race fallback.  Both
            # paths retain the same provider session and replace the unpublished
            # draft before it reaches the coordinator.
            while guidance_mailbox is not None and guidance_mailbox.has_pending():
                markdown = await driver.run_writeup(
                    manifest, scratch, flag, notes, cancel_event, progress
                )
            if guidance_mailbox is not None:
                guidance_mailbox.reject_all("solve_finished")
            driver.guidance_mailbox = None
            writer.emit("writeup", flag=flag, writeup_markdown=markdown, terminal=False)
            writer.state(
                status="releasing", outcome="completed", terminal=False,
                flag=flag, writeup_markdown=markdown,
                private_notes=bounded_checkpoint_notes(notes),
                solver_artifact=solver_artifact_payload,
            )
            release_status = "completed"
            release_payload = {"flag": flag, "writeup_markdown": markdown}
            return True
        except asyncio.CancelledError:
            if writer:
                current = _load_optional_state(active, manifest.job_id)
                flag = current.get("flag") if isinstance(current.get("flag"), str) else None
                preserved_notes = current.get("private_notes") if isinstance(current.get("private_notes"), str) else ""
                notes = bounded_checkpoint_notes(preserved_notes or notes)
                if deadline_expired.is_set():
                    error = SolverError(
                        "timeout",
                        "solver 작업이 최대 실행 시간을 초과했습니다.",
                        "writeup" if flag else "solve",
                        "temporary",
                        True,
                    )
                    writer.emit("error", error=error.public(), flag=flag, terminal=False)
                    writer.state(
                        status="releasing", outcome="failed", terminal=False,
                        flag=flag, error=error.public(),
                        private_notes=bounded_checkpoint_notes(notes),
                        solver_artifact=solver_artifact_payload,
                    )
                    release_status = "failed"
                    release_payload = {"error": error.public()}
                    if flag:
                        release_payload["flag"] = flag
                elif self.stopping:
                    writer.emit("status", status="interrupted", flag=flag, terminal=False)
                    writer.state(
                        status="interrupted",
                        terminal=False,
                        flag=flag,
                        private_notes=current.get("private_notes", ""),
                        solver_artifact=solver_artifact_payload,
                    )
                elif remote_requested.is_set():
                    request_error = remote_request_result.get("error")
                    request_note = remote_request_result.get("note")
                    if isinstance(request_error, WorkerRefusal):
                        error = request_error.error
                        outcome = "refused"
                    elif not isinstance(request_note, str):
                        error = SolverError(
                            "remote_request_invalid_state",
                            "request-remote 요청 내용을 확인할 수 없습니다.",
                            "solve",
                            "safety",
                            False,
                        )
                        outcome = "refused"
                    else:
                        remote_context = {
                            "endpoint": "제공된 원격 접속 정보로 진행할 수 없어",
                            "none": "원격 대상 없음으로 설정되어 있지만",
                        }.get(manifest.remote_mode)
                        request_message = (
                            f"Solver가 {remote_context} 추가 입력을 요청했습니다: {request_note}"
                            if remote_context
                            else f"Solver가 원격 접속 정보를 요청했습니다: {request_note}"
                        )
                        error = SolverError(
                            "remote_input_required",
                            request_message,
                            "solve",
                            "input",
                            False,
                        )
                        outcome = "needs_input"
                        notes = bounded_checkpoint_notes(
                            f"{notes}\n\n# Remote input requested\n\n{request_note}"
                            if notes else f"# Remote input requested\n\n{request_note}"
                        )
                    writer.emit("error", error=error.public(), terminal=False)
                    writer.state(
                        status="releasing",
                        outcome=outcome,
                        terminal=False,
                        error=error.public(),
                        private_notes=notes,
                        solver_artifact=solver_artifact_payload,
                    )
                    release_status = outcome
                    release_payload = {"error": error.public()}
                else:
                    writer.emit("cancelled", flag=flag, terminal=False)
                    writer.state(
                        status="releasing", outcome="cancelled", terminal=False,
                        flag=flag, private_notes=bounded_checkpoint_notes(notes),
                        solver_artifact=solver_artifact_payload,
                    )
                    release_status = "cancelled"
                    if flag:
                        release_payload["flag"] = flag
            return True
        except WorkerRefusal as exc:
            if writer:
                current = _load_optional_state(active, manifest.job_id)
                preserved_flag = current.get("flag") if isinstance(current.get("flag"), str) else None
                preserved_notes = current.get("private_notes") if isinstance(current.get("private_notes"), str) else ""
                notes = bounded_checkpoint_notes(preserved_notes or notes)
                if exc.error.code == "credential_required":
                    needs_credential = True
                    _write_json(
                        active / "credential-request.json",
                        {"protocol": EXCHANGE_PROTOCOL, "job_id": manifest.job_id, "requested_at": time.time()},
                    )
                    writer.emit("status", status="awaiting_credential")
                    writer.state(
                        status="awaiting_credential",
                        terminal=False,
                        flag=preserved_flag,
                        private_notes=preserved_notes,
                        solver_artifact=solver_artifact_payload,
                    )
                    # No provider process was started. The finally block first
                    # removes the credential-free prepared workspace, then
                    # advertises a clean slot for atomic credential restaging.
                else:
                    release_status = "flag_found" if preserved_flag else "refused"
                    writer.emit("error", error=exc.error.public(), flag=preserved_flag, terminal=False)
                    writer.state(
                        status="releasing",
                        outcome=release_status,
                        terminal=False,
                        flag=preserved_flag,
                        private_notes=notes,
                        error=exc.error.public(),
                        solver_artifact=solver_artifact_payload,
                    )
                    release_payload = {"error": exc.error.public()}
                    if preserved_flag:
                        release_payload["flag"] = preserved_flag
            return True
        except Exception as exc:
            raw = exc.payload if isinstance(exc, AppServerFailure) else exc
            error = normalize_provider_failure(
                raw,
                stage=(
                    "writeup"
                    if manifest is not None and manifest.job_mode == "writeup_refine"
                    else "writeup" if writer and _state_has_flag(active) else "solve"
                ),
                model=(manifest.configuration.model if manifest is not None else None),
                authenticated_preflight=bool(
                    driver is not None
                    and getattr(driver, "chatgpt_preflight_verified", False)
                ),
            )
            if writer:
                current = _load_optional_state(active, manifest.job_id)
                flag = current.get("flag") if isinstance(current.get("flag"), str) else None
                preserved_notes = current.get("private_notes") if isinstance(current.get("private_notes"), str) else ""
                notes = bounded_checkpoint_notes(preserved_notes or notes)
                release_status = "flag_found" if flag else "failed"
                release_payload = {"error": error.public()}
                if flag:
                    release_payload["flag"] = flag
                writer.emit("error", error=error.public(), flag=flag, terminal=False)
                writer.state(
                    status="releasing", outcome=release_status, terminal=False,
                    private_notes=bounded_checkpoint_notes(notes),
                    solver_artifact=solver_artifact_payload,
                    **release_payload,
                )
            return True
        finally:
            if guidance_mailbox is not None and release_status:
                guidance_mailbox.reject_all("job_finished")
            if credential:
                credential.erase()
            if cancel_watcher:
                cancel_watcher.cancel()
                await asyncio.gather(cancel_watcher, return_exceptions=True)
            if attachment_watcher:
                attachment_watcher.cancel()
                await asyncio.gather(attachment_watcher, return_exceptions=True)
            if remote_request_watcher:
                remote_request_watcher.cancel()
                await asyncio.gather(remote_request_watcher, return_exceptions=True)
            if deadline_watcher:
                deadline_watcher.cancel()
                await asyncio.gather(deadline_watcher, return_exceptions=True)
            if driver:
                try:
                    await asyncio.wait_for(driver.close(), timeout=DRIVER_CLOSE_TIMEOUT_SECONDS)
                except Exception:
                    # The namespace-wide cleaner below is authoritative.  A
                    # provider-specific close error must not strand a clean
                    # namespace and its scratch tree forever.
                    pass
            if needs_credential:
                try:
                    self.process_assertion()
                    self._remove_job_scratch(job_root)
                    assert_scratch_root_clean(self.scratch_root)
                except Exception:
                    self.clean = False
                    self._publish_worker(reason="scratch_cleanup_failed")
                    self._require_restart("scratch_cleanup_failed")
                else:
                    self.clean = True
                    self._publish_worker(reason="awaiting_credential")
            elif release_status and writer:
                cleanup_error: SolverError | None = None
                try:
                    await self.process_cleaner(getattr(driver, "pid", None))
                    self.process_assertion()
                except Exception:
                    cleanup_error = SolverError(
                        "process_cleanup_failed",
                        "작업 프로세스 정리를 확인하지 못해 다음 작업을 차단했습니다.",
                        "cleanup",
                        "safety",
                        False,
                    )
                try:
                    if cleanup_error is None:
                        if scratch is not None:
                            current_artifact = _capture_solver_artifact(scratch / "solver.py")
                            if current_artifact is not None:
                                solver_artifact_payload = current_artifact.payload()
                        self._remove_job_scratch(job_root)
                        assert_scratch_root_clean(self.scratch_root)
                except Exception:
                    if cleanup_error is None:
                        cleanup_error = SolverError(
                            "scratch_cleanup_failed",
                            "solver 임시 작업 파일을 정리하지 못해 다음 작업을 차단했습니다.",
                            "cleanup",
                            "storage",
                            False,
                        )
                if cleanup_error is not None:
                    try:
                        writer.emit("error", error=cleanup_error.public(), terminal=False)
                        writer.state(
                            status="cleanup_blocked", outcome=release_status, terminal=False,
                            private_notes=bounded_checkpoint_notes(notes),
                            solver_artifact=solver_artifact_payload,
                            **release_payload, cleanup_error=cleanup_error.public(),
                        )
                    finally:
                        # Keeping this process alive would leave a stale scratch
                        # tree and falsely healthy heartbeat.  Docker restarts
                        # it in a fresh PID namespace with an empty job scratch even
                        # if persisting the diagnostic also encounters an I/O
                        # failure.
                        self._require_restart(cleanup_error.code)
                else:
                    terminal_notes = bounded_checkpoint_notes(notes)
                    # The terminal state (including private retry facts) is
                    # durable before the public release event.  If the worker
                    # dies between these writes, the existing terminal-state
                    # recovery path emits release without rerunning the model.
                    writer.state(
                        status=release_status,
                        terminal=True,
                        private_notes=terminal_notes,
                        solver_artifact=solver_artifact_payload,
                        **release_payload,
                    )
                    writer.emit("released", status=release_status, terminal=True, **release_payload)
                    self.clean = True
                    self._publish_worker()
            elif self.stopping and driver:
                try:
                    await self.process_cleaner(getattr(driver, "pid", None))
                    self.process_assertion()
                    self.clean = True
                    self._remove_job_scratch(job_root)
                    assert_scratch_root_clean(self.scratch_root)
                    self._publish_worker()
                except Exception:
                    self._require_restart("process_cleanup_failed")

    def _remove_job_scratch(self, root: Path | None) -> None:
        if root is None or not root.exists():
            return
        if root.is_symlink() or root.resolve().parent != self.scratch_root.resolve():
            raise WorkerRefusal("scratch_cleanup_failed", "solver 임시 작업 경로를 안전하게 정리할 수 없습니다.")

        if os.name == "posix":
            # Archives commonly contain mode-000 directories. The regular
            # shutil traversal cannot enter them and previously mislabeled the
            # resulting PermissionError as a process cleanup failure. At this
            # point the private PID namespace is clean, so use the same
            # descriptor-relative, no-symlink cleanup proven at crash recovery.
            recover_crash_scratch(self.scratch_root)
            return

        def remove_readonly(operation, path, failure):
            # Windows maps chmod(0400) to its read-only attribute. Production is
            # Linux, but the same cleanup proof is exercised on development
            # hosts without weakening the read-only manual during execution.
            if os.name != "nt":
                raise failure
            details = os.lstat(path)
            os.chmod(path, 0o700 if stat.S_ISDIR(details.st_mode) else 0o600, follow_symlinks=False)
            operation(path)

        shutil.rmtree(root, onexc=remove_readonly)

    async def _heartbeat(self, stop: asyncio.Event, *, interval: float = 1.0) -> None:
        while not stop.is_set():
            self._publish_worker(reason="awaiting_credential" if self.clean and (self.exchange / "active" / "credential-request.json").exists() else None)
            try:
                await asyncio.wait_for(stop.wait(), timeout=interval)
            except TimeoutError:
                pass

    async def serve(self, *, interval: float = 0.5) -> None:
        stop = asyncio.Event()
        loop = asyncio.get_running_loop()

        def request_stop():
            self.stopping = True
            stop.set()
            if self.current_task and not self.current_task.done():
                self.current_task.cancel()

        for signum in (signal.SIGTERM, signal.SIGINT):
            try:
                loop.add_signal_handler(signum, request_stop)
            except (NotImplementedError, RuntimeError):
                pass
        self.prepare()
        self.current_task = asyncio.create_task(self.attest_runtime())
        outcome = await asyncio.gather(self.current_task, return_exceptions=True)
        self.current_task = None
        if stop.is_set():
            return
        if outcome and isinstance(outcome[0], BaseException):
            self._require_restart("runtime_attestation_failed")
            return
        if not self.runtime_ready or not self.sandbox_attested:
            # Docker restart policy gives a coordinator time to remove an
            # interrupted hidden stage, then retries the full attestation in a
            # fresh PID namespace.  Never idle in a falsely ready container.
            return
        heartbeat = asyncio.create_task(self._heartbeat(stop))
        try:
            while not stop.is_set():
                self.current_task = asyncio.create_task(self.process_active())
                outcome = await asyncio.gather(self.current_task, return_exceptions=True)
                self.current_task = None
                if outcome and isinstance(outcome[0], BaseException) and not stop.is_set():
                    self._require_restart("worker_task_failed")
                if self.restart_required:
                    stop.set()
                    break
                if stop.is_set():
                    break
                try:
                    await asyncio.wait_for(stop.wait(), timeout=interval)
                except TimeoutError:
                    pass
        finally:
            stop.set()
            heartbeat.cancel()
            await asyncio.gather(heartbeat, return_exceptions=True)


def _validate_challenge_tree(challenge: Path) -> None:
    if challenge.is_symlink() or not challenge.is_dir():
        raise WorkerRefusal("invalid_challenge_stage", "문제 파일 디렉터리를 확인할 수 없습니다.")
    root = challenge.resolve()
    count = 0
    for current, directories, files in os.walk(challenge, followlinks=False):
        current_path = Path(current)
        if not current_path.resolve().is_relative_to(root):
            raise WorkerRefusal("invalid_challenge_stage", "문제 파일 경로가 작업 밖을 가리킵니다.")
        for name in directories + files:
            count += 1
            if count > 100_000:
                raise WorkerRefusal("too_many_challenge_files", "문제 파일 개수가 허용 범위를 넘었습니다.")
            path = current_path / name
            info = path.lstat()
            if stat.S_ISLNK(info.st_mode) or (name in files and (not stat.S_ISREG(info.st_mode) or info.st_nlink != 1)):
                raise WorkerRefusal("invalid_challenge_stage", "문제 파일에 허용하지 않는 링크 또는 특수 파일이 있습니다.")


def _existing_terminal_state(active: Path, job_id: str) -> bool:
    state = _load_optional_state(active, job_id)
    return state.get("terminal") is True


def _load_events(active: Path, job_id: str) -> list[dict[str, Any]]:
    directory = active / "events"
    if not directory.exists() or directory.is_symlink():
        return []
    result = []
    expected = 1
    for path in sorted(directory.glob("[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9].json")):
        event = _read_json(path, MAX_RESULT_CONTROL_BYTES + 256 * 1024)
        if (
            event.get("protocol") != EXCHANGE_PROTOCOL
            or event.get("job_id") != job_id
            or event.get("sequence") != expected
        ):
            raise WorkerRefusal("invalid_worker_events", "worker 이벤트 순서를 확인할 수 없습니다.")
        result.append(event)
        expected += 1
    return result


def _load_optional_state(active: Path, job_id: str) -> dict[str, Any]:
    path = active / "state.json"
    if not path.exists():
        return {}
    state = _read_json(path, MAX_RESULT_CONTROL_BYTES + 256 * 1024)
    if state.get("protocol") != EXCHANGE_PROTOCOL or state.get("job_id") != job_id:
        raise WorkerRefusal("invalid_worker_state", "worker 재개 상태를 확인할 수 없습니다.")
    return state


def _state_has_flag(active: Path) -> bool:
    try:
        state = _read_json(active / "state.json", MAX_RESULT_CONTROL_BYTES + 256 * 1024)
        return isinstance(state.get("flag"), str) and bool(state["flag"])
    except WorkerRefusal:
        return False


async def _watch_cancel(path: Path, event: asyncio.Event) -> None:
    while not event.is_set():
        if path.exists():
            event.set()
            return
        await asyncio.sleep(0.2)


def _install_live_attachments(source: Path, destination: Path, visible: Path | None) -> int:
    """Add uploaded files to an existing solve without replacing agent work."""

    if not source.exists():
        return 0
    if source.is_symlink() or not source.is_dir() or destination.is_symlink():
        raise ValueError("live attachment directory is invalid")
    destination.mkdir(mode=0o700, exist_ok=True)
    if not destination.is_dir():
        raise ValueError("live attachment directory is invalid")
    if visible is not None:
        if visible.is_symlink() or not visible.is_dir() or not os.path.samefile(source, visible):
            raise ValueError("read-only attachment view does not match")
    added = 0
    for item in source.iterdir():
        if not item.name.startswith("live-"):
            continue
        info = item.lstat()
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise ValueError("live attachment is not a regular file")
        target = destination / item.name
        if target.exists() or target.is_symlink():
            continue
        if visible is not None:
            readonly = visible / item.name
            view_info = readonly.lstat()
            if (
                not stat.S_ISREG(view_info.st_mode)
                or view_info.st_nlink != 1
                or view_info.st_size != info.st_size
                or not os.path.samefile(item, readonly)
            ):
                raise ValueError("read-only attachment file does not match")
            target.symlink_to(readonly)
        else:
            with item.open("rb") as input_stream, target.open("xb") as output_stream:
                shutil.copyfileobj(input_stream, output_stream, length=1024 * 1024)
            target.chmod(0o600)
        added += 1
    return added


async def _watch_live_attachments(
    source: Path, destination: Path, visible: Path | None, writer: EventWriter
) -> None:
    last_error = None
    while True:
        install = asyncio.create_task(
            asyncio.to_thread(_install_live_attachments, source, destination, visible)
        )
        try:
            added = await asyncio.shield(install)
        except asyncio.CancelledError:
            # A copy running in a thread must finish before scratch cleanup.
            await asyncio.gather(install, return_exceptions=True)
            raise
        except (OSError, ValueError) as exc:
            error = str(exc)
            if error != last_error:
                writer.emit("activity", phase="attachment_sync_failed", summary=error)
                last_error = error
        else:
            last_error = None
            if added:
                writer.emit("activity", phase="attachment_added", summary=f"{added} new attachment(s) available in attachments/")
        await asyncio.sleep(0.5)


async def _enforce_deadline(
    deadline_unix: float,
    expired: asyncio.Event,
    cancelled: asyncio.Event,
    task: asyncio.Task | None,
    *,
    grace_seconds: float = 0.25,
) -> None:
    remaining = max(0.0, deadline_unix - time.time())
    if remaining:
        await asyncio.sleep(remaining)
    expired.set()
    # Let the app-server receive ``turn/interrupt`` first. A short, fixed grace
    # retains an operator-configured absolute cap if the provider stops responding.
    cancelled.set()
    if grace_seconds:
        await asyncio.sleep(grace_seconds)
    if task and not task.done():
        task.cancel()



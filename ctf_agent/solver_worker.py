def _parse_structured_output(value: object) -> dict[str, Any]:
    if not isinstance(value, str) or not value or len(value) > MAX_OUTPUT_TEXT:
        raise AppServerFailure({"code": "invalid_response"})
    try:
        result = json.loads(value, object_pairs_hook=lambda pairs: _unique_pairs(pairs), parse_constant=lambda _: (_ for _ in ()).throw(ValueError()))
    except (ValueError, TypeError, RecursionError) as exc:
        raise AppServerFailure({"code": "invalid_response"}) from exc
    if not isinstance(result, dict):
        raise AppServerFailure({"code": "invalid_response"})
    return result


def _unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate key")
        result[key] = value
    return result



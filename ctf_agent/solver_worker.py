def _bounded_soft_turn_outcome(
    message: object,
    *,
    command_execution_seen: bool,
) -> SolverError | str | None:
    """Return a fixed soft-failure value without retaining provider prose."""

    if not isinstance(message, str) or not message:
        return None
    try:
        if len(message.encode("utf-8")) > MAX_SOFT_MESSAGE_BYTES:
            return None
    except UnicodeError:
        return None
    refusal = normalize_provider_soft_refusal(
        message,
        stage="solve",
        command_execution_seen=command_execution_seen,
    )
    if refusal is not None:
        return SolverError(
            code=refusal.code,
            message=refusal.message,
            stage=refusal.stage,
            category=refusal.category,
            retryable=refusal.retryable,
            provider_code=refusal.provider_code,
        )

    text = re.sub(r"\s+", " ", message).strip()
    if (
        text
        and len(text.split()) <= 120
        and _PROGRESS_ONLY_PROMISE.search(text)
        and not _PROGRESS_ONLY_EVIDENCE.search(text)
    ):
        return "progress_only"
    return None


def _raise_soft_refusal(error: SolverError) -> None:
    """Raise only the already-normalized fields from a soft provider refusal."""

    raise WorkerRefusal(
        error.code,
        error.message,
        category=error.category,
        retryable=error.retryable,
        stage=error.stage,
        provider_code=error.provider_code,
    )


class WorkerRefusal(RuntimeError):
    """A safe, client-displayable worker refusal."""

    def __init__(self, code: str, message: str, *, category: str = "safety", retryable: bool = False,
                 stage: str = "worker", provider_code: str | None = None,
                 requirements: tuple[str, ...] = ()):
        super().__init__(message)
        self.error = SolverError(
            code=code,
            message=message,
            stage=stage,
            category=category,
            retryable=retryable,
            provider_code=provider_code,
            requirements=requirements,
        )



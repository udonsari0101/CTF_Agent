    def command_arguments(self, manifest: JobManifest, schema: dict[str, Any]) -> list[str]:
        session = self._session_uuid(manifest.job_id)
        if self.session_id is not None and not secrets_compare(self.session_id, session):
            raise WorkerRefusal("provider_session_mismatch", "Claude 작업 세션을 확인할 수 없습니다.")
        self.session_id = session
        writeup_only = getattr(manifest, "job_mode", "solve") == "writeup_refine"
        ultracode = manifest.configuration.ultracode and not writeup_only
        allowed_tools = () if writeup_only else (
            *self.ALLOWED_TOOLS, *(("Workflow",) if ultracode else ())
        )
        tools = ",".join(allowed_tools)
        settings_payload = (
            {
                **self.SETTINGS,
                "permissions": {
                    "defaultMode": "dontAsk",
                    "allow": [],
                    "deny": [*self.ALLOWED_TOOLS, "mcp__*"],
                },
            }
            if writeup_only
            else {
                **self.SETTINGS,
                "ultracode": ultracode,
                "permissions": {
                    **self.SETTINGS["permissions"],
                    "allow": list(allowed_tools),
                },
            }
        )
        settings = json.dumps(
            settings_payload,
            ensure_ascii=True,
            allow_nan=False,
            separators=(",", ":"),
        )
        schema_text = json.dumps(schema, ensure_ascii=True, allow_nan=False, separators=(",", ":"))
        challenge_root = self.challenge.parent
        skills = self.challenge.parents[1] / "skills"
        arguments = [
            "--restricted",
            "-p",
            "--output-format",
            "stream-json",
            "--verbose",
            "--include-partial-messages",
            "--json-schema",
            schema_text,
        ]
        if not writeup_only:
            arguments.append("--forward-subagent-text")
        if self.turn_count == 0:
            arguments.extend(("--session-id", session))
        else:
            arguments.extend(("--resume", session))
        arguments.extend(
            (
                "--model",
                manifest.configuration.model,
                "--effort",
                manifest.configuration.reasoning_effort,
                "--add-dir",
                str(challenge_root),
                "--add-dir",
                str(skills),
                "--tools",
                tools,
                "--disallowedTools",
                ",".join((*self.ALLOWED_TOOLS, "mcp__*"))
                if writeup_only
                else "mcp__*",
                "--permission-mode",
                "dontAsk",
                "--permission-prompts",
                "none",
                "--disable-slash-commands",
                "--no-chrome",
                "--strict-mcp-config",
                "--mcp-config",
                '{"mcpServers":{}}',
                "--prompt-suggestions",
                "false",
                "--settings",
                settings,
            )
        )
        if allowed_tools:
            tools_index = arguments.index("--tools") + 2
            arguments[tools_index:tools_index] = ["--allowedTools", tools]
        return arguments

    @staticmethod
    def _model_matches(selected: str, actual: object) -> bool:
        if not isinstance(actual, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._:-]{0,199}", actual):
            return False
        lowered = actual.lower()
        resolved = re.fullmatch(r"claude-(fable|opus|sonnet|haiku)(?:-[a-z0-9]+)*", lowered)
        if selected in {"default", "best"}:
            return lowered in {"default", "best"} or resolved is not None
        return selected == lowered or (resolved is not None and resolved.group(1) == selected)

    @staticmethod
    def _policy_refusal(event: Mapping[str, Any]) -> bool:
        candidates: list[object] = [event.get("stop_reason"), event.get("stop_details")]
        message = event.get("message")
        if isinstance(message, Mapping):
            candidates.extend((message.get("stop_reason"), message.get("stop_details")))
        for candidate in candidates:
            if isinstance(candidate, str) and candidate.lower() == "refusal":
                return True
            if isinstance(candidate, Mapping):
                for key in ("type", "category", "code", "reason"):
                    value = candidate.get(key)
                    if isinstance(value, str) and len(value) <= 100 and re.search(r"(?:refusal|cyber|policy|safety)", value, re.I):
                        return True
        return False

    async def _stderr_reader_claude(self, process: asyncio.subprocess.Process) -> None:
        if process.stderr is None:
            return
        retained = bytearray()
        total = 0
        while chunk := await process.stderr.read(4096):
            total += len(chunk)
            if total > MAX_CLAUDE_STREAM_BYTES:
                self.stderr_categories.add("overflow")
                continue
            lowered = chunk.lower()
            if b"permission denied" in lowered:
                self.stderr_categories.add("permission_denied")
            elif b"rate limit" in lowered:
                self.stderr_categories.add("rate_limit")
            elif b"refusal" in lowered or b"policy" in lowered:
                self.stderr_categories.add("policy")
            elif lowered.strip():
                self.stderr_categories.add("other")
            if len(retained) < 1024:
                retained.extend(chunk[: 1024 - len(retained)])
        if retained:
            self.safe_startup_stderr = sanitize_startup_stderr(bytes(retained))

    async def _read_stream(self, process: asyncio.subprocess.Process, manifest: JobManifest, progress) -> dict[str, Any]:
        if process.stdout is None:
            raise AppServerFailure({"code": "provider_stream_closed"})
        self._last_turn_soft_outcome = None
        total = 0
        events = 0
        initialized = False
        result: dict[str, Any] | None = None
        session = self.session_id
        while line := await process.stdout.readline():
            total += len(line)
            events += 1
            if len(line) > MAX_RPC_LINE or total > MAX_CLAUDE_STREAM_BYTES or events > MAX_CLAUDE_EVENTS:
                raise WorkerRefusal("provider_response_too_large", "Claude 응답이 허용 범위를 넘었습니다.")
            try:
                event = json.loads(
                    line.decode("utf-8", errors="strict"),
                    object_pairs_hook=_unique_pairs,
                    parse_constant=lambda _: (_ for _ in ()).throw(ValueError()),
                )
            except (ValueError, UnicodeError, TypeError, RecursionError) as exc:
                raise AppServerFailure({"code": "invalid_response"}) from exc
            if not isinstance(event, dict):
                raise AppServerFailure({"code": "invalid_response"})
            event_type = event.get("type")
            if not isinstance(event_type, str) or not re.fullmatch(r"[a-z][a-z0-9_]{0,63}", event_type):
                raise AppServerFailure({"code": "invalid_response"})
            event_session = event.get("session_id")
            subagent_event = isinstance(event.get("parent_tool_use_id"), str)
            if event_session is not None and event_session != session and not subagent_event:
                raise WorkerRefusal("provider_session_mismatch", "Claude 작업 세션이 실행 중 변경되었습니다.")
            if self._policy_refusal(event):
                raise AppServerFailure(
                    {
                        "code": "policy_security",
                        "category": "policy_security",
                        "provider_code": "CVP",
                        "retryable": False,
                    }
                )
            if subagent_event and event_type in {"assistant", "user"}:
                message = event.get("message")
                content = message.get("content") if isinstance(message, Mapping) else None
                if event_type == "assistant" and isinstance(content, list):
                    text_parts = [
                        block["text"] for block in content[:200]
                        if isinstance(block, Mapping)
                        and block.get("type") == "text"
                        and isinstance(block.get("text"), str)
                    ]
                    if text_parts:
                        await self._report_activity(
                            "completed", "agent", "Subagent update",
                            message="\n".join(text_parts)[:MAX_SOFT_MESSAGE_BYTES],
                        )
                continue
            if event_type == "system" and event.get("subtype") == "init":
                if (
                    initialized
                    or event_session != session
                    or not self._model_matches(manifest.configuration.model, event.get("model"))
                    or event.get("effort", manifest.configuration.reasoning_effort)
                    != manifest.configuration.reasoning_effort
                ):
                    raise WorkerRefusal("model_mismatch", "Claude가 선택한 모델과 다른 모델을 반환했습니다.", category="model")
                if event.get("claude_code_version") != self.expected_version:
                    raise WorkerRefusal("claude_version_mismatch", "검증된 Claude worker 버전과 실행 버전이 일치하지 않습니다.")
                if event.get("permissionMode") != "dontAsk" or event.get("slash_commands") != []:
                    raise WorkerRefusal("tool_policy_mismatch", "Claude 실행 권한 제한을 확인하지 못했습니다.")
                returned_tools = event.get("tools")
                expected_tools = {
                    *(
                        ()
                        if getattr(manifest, "job_mode", "solve") == "writeup_refine"
                        else (*self.ALLOWED_TOOLS, *(("Workflow",) if manifest.configuration.ultracode else ()))
                    ),
                    "StructuredOutput",
                }
                if not isinstance(returned_tools, list) or set(returned_tools) != expected_tools:
                    raise WorkerRefusal("tool_policy_mismatch", "Claude 도구 제한을 확인하지 못했습니다.")
                mcp_servers = event.get("mcp_servers", [])
                if mcp_servers not in ([], None):
                    raise WorkerRefusal("unexpected_remote_tool", "Claude MCP 도구가 활성화되어 실행을 거부했습니다.")
                initialized = True
                continue
            if event_type == "assistant":
                if not initialized:
                    raise AppServerFailure({"code": "invalid_response"})
                safe_error = event.get("error")
                if safe_error in {"authentication_failed", "auth_required", "invalid_auth"}:
                    raise AppServerFailure({"code": "auth_required", "retryable": False})
                if safe_error in {"rate_limit", "rate_limit_error", "quota_exceeded"}:
                    raise AppServerFailure({"code": "quota_exceeded", "retryable": True})
                if safe_error in {"model_not_found", "model_unavailable"}:
                    raise AppServerFailure({"code": "model_unavailable", "retryable": False})
                message = event.get("message")
                content = message.get("content") if isinstance(message, Mapping) else None
                if isinstance(content, list):
                    text_parts: list[str] = []
                    text_bytes = 0
                    for block in content[:200]:
                        if not isinstance(block, Mapping):
                            continue
                        if block.get("type") == "text" and isinstance(block.get("text"), str):
                            encoded = block["text"].encode("utf-8", errors="ignore")
                            if text_bytes + len(encoded) <= MAX_SOFT_MESSAGE_BYTES:
                                text_parts.append(block["text"])
                                text_bytes += len(encoded)
                            continue
                        if block.get("type") != "tool_use":
                            continue
                        name = block.get("name")
                        allowed_tools = {
                            *(
                                ()
                                if getattr(manifest, "job_mode", "solve") == "writeup_refine"
                                else (*self.ALLOWED_TOOLS, *(("Workflow",) if manifest.configuration.ultracode else ()))
                            ),
                            "StructuredOutput",
                        }
                        if name not in allowed_tools:
                            raise WorkerRefusal("unexpected_remote_tool", "Claude가 허용하지 않은 도구를 요청했습니다.")
                        if name != "StructuredOutput":
                            self._discovery_command_execution_seen = True
                            await progress("executing" if name == "Bash" else "inspecting_files")
                            tool_input = block.get("input")
                            command = (
                                tool_input.get("command")
                                if name == "Bash" and isinstance(tool_input, Mapping)
                                else tool_input.get("query")
                                if name == "WebSearch" and isinstance(tool_input, Mapping)
                                else None
                            )
                            await self._report_activity(
                                "started",
                                "shell"
                                if name == "Bash"
                                else "web_search"
                                if name == "WebSearch"
                                else "file",
                                "명령 실행"
                                if name == "Bash"
                                else "웹 검색"
                                if name == "WebSearch"
                                else "파일 검사",
                                command=command,
                            )
                    if text_parts:
                        await self._report_activity(
                            "completed",
                            "analysis",
                            "모델 응답",
                            message="\n".join(text_parts),
                        )
                        outcome = _bounded_soft_turn_outcome(
                            "\n".join(text_parts),
                            command_execution_seen=self._discovery_command_execution_seen,
                        )
                        if isinstance(outcome, SolverError):
                            _raise_soft_refusal(outcome)
                        self._last_turn_soft_outcome = (
                            outcome if isinstance(outcome, str) else None
                        )
                continue
            if event_type == "user":
                message = event.get("message")
                content = message.get("content") if isinstance(message, Mapping) else None
                if isinstance(content, list):
                    for block in content[:200]:
                        if not isinstance(block, Mapping) or block.get("type") != "tool_result":
                            continue
                        raw_output = block.get("content")
                        if isinstance(raw_output, list):
                            raw_output = "\n".join(
                                item.get("text", "")
                                for item in raw_output
                                if isinstance(item, Mapping)
                                and item.get("type") == "text"
                                and isinstance(item.get("text"), str)
                            )
                        await self._report_activity(
                            "completed",
                            "tool",
                            "도구 출력",
                            output=raw_output,
                        )
                continue
            if event_type == "system" and event.get("subtype") == "api_retry":
                # Retry diagnostics may contain provider text.  Retain none of
                # it; only the bounded progress category reaches the web app.
                await progress("waiting_for_model")
                continue
            if event_type == "result":
                if not initialized or result is not None or event_session != session:
                    raise AppServerFailure({"code": "invalid_response"})
                if event.get("subtype") != "success" or event.get("is_error") is not False:
                    if event.get("api_error_status") in {401, "401"}:
                        raise AppServerFailure({"code": "auth_required", "retryable": False})
                    if event.get("api_error_status") in {429, "429"}:
                        raise AppServerFailure({"code": "quota_exceeded", "retryable": True})
                    raise AppServerFailure({"code": "provider_error", "retryable": True})
                result_outcome = _bounded_soft_turn_outcome(
                    event.get("result"),
                    command_execution_seen=self._discovery_command_execution_seen,
                )
                if isinstance(result_outcome, SolverError):
                    _raise_soft_refusal(result_outcome)
                if isinstance(result_outcome, str):
                    self._last_turn_soft_outcome = result_outcome
                structured = event.get("structured_output")
                if not isinstance(structured, dict):
                    if self._last_turn_soft_outcome == "progress_only":
                        structured = {"flag": "", "private_notes": ""}
                    else:
                        raise AppServerFailure({"code": "invalid_response"})
                flag = structured.get("flag")
                notes = structured.get("private_notes")
                if isinstance(flag, str) and flag.strip():
                    self._last_turn_soft_outcome = None
                elif isinstance(notes, str):
                    notes_outcome = _bounded_soft_turn_outcome(
                        notes,
                        command_execution_seen=self._discovery_command_execution_seen,
                    )
                    if isinstance(notes_outcome, SolverError):
                        _raise_soft_refusal(notes_outcome)
                    if notes_outcome == "progress_only":
                        self._last_turn_soft_outcome = "progress_only"
                        structured = dict(structured)
                        structured["private_notes"] = ""
                result = structured
        await process.wait()
        if process.returncode != 0 or result is None:
            raise AppServerFailure({"code": "provider_stream_closed" if result is None else "provider_error"})
        return result

    async def _turn(self, manifest: JobManifest, prompt: str, schema: dict[str, Any], cancelled: asyncio.Event, progress) -> dict[str, Any]:
        if not self.credential_path or not self.credential_path.is_file():
            raise WorkerRefusal("credential_required", "Claude 인증정보를 다시 준비해야 합니다.", category="auth", retryable=True)
        initial_guidance: list[GuidanceRecord] = []
        if self.guidance_mailbox is not None:
            initial_guidance = self.guidance_mailbox.take_nowait_many()
            if initial_guidance:
                prompt = _append_solver_guidance(prompt, initial_guidance)
        encoded = prompt.encode("utf-8")
        if not encoded or len(encoded) > MAX_CLAUDE_PROMPT_BYTES:
            if self.guidance_mailbox is not None:
                for guidance in initial_guidance:
                    self.guidance_mailbox.release(guidance)
            raise WorkerRefusal("provider_prompt_too_large", "Claude 요청이 허용 크기를 넘었습니다.")
        try:
            process = await self._spawn(self.command_arguments(manifest, schema))
        except BaseException:
            if self.guidance_mailbox is not None:
                for guidance in initial_guidance:
                    self.guidance_mailbox.release(guidance)
            raise
        self.stderr_task = asyncio.create_task(self._stderr_reader_claude(process))
        cancel_task = asyncio.create_task(cancelled.wait())
        drain_task: asyncio.Task | None = None
        stream_task: asyncio.Task | None = None
        guidance_delivered = False
        try:
            if process.stdin is None:
                raise AppServerFailure({"code": "provider_unavailable"})
            process.stdin.write(encoded)
            drain_task = asyncio.create_task(process.stdin.drain())
            done, _ = await asyncio.wait((drain_task, cancel_task), return_when=asyncio.FIRST_COMPLETED)
            if cancel_task in done and cancel_task.result():
                raise asyncio.CancelledError
            await drain_task
            if self.guidance_mailbox is not None:
                for guidance in initial_guidance:
                    self.guidance_mailbox.delivered(guidance, "next_turn")
                guidance_delivered = True
            process.stdin.close()
            stream_task = asyncio.create_task(self._read_stream(process, manifest, progress))
            loop = asyncio.get_running_loop()
            next_heartbeat = loop.time() + MODEL_WAIT_HEARTBEAT_SECONDS
            while True:
                done, _ = await asyncio.wait(
                    (stream_task, cancel_task),
                    timeout=max(0, next_heartbeat - loop.time()),
                    return_when=asyncio.FIRST_COMPLETED,
                )
                if cancel_task in done and cancel_task.result():
                    raise asyncio.CancelledError
                if stream_task in done:
                    value = await stream_task
                    self.turn_count += 1
                    return value
                await progress("waiting_for_model")
                next_heartbeat = loop.time() + MODEL_WAIT_HEARTBEAT_SECONDS
        except asyncio.CancelledError:
            # Both a user cancellation and the job deadline take the graceful
            # provider path first.  The process-group escalation inside
            # _stop_current keeps helper children from surviving the turn.
            await self._stop_current(interrupt=True)
            raise
        finally:
            if self.guidance_mailbox is not None and not guidance_delivered:
                for guidance in initial_guidance:
                    self.guidance_mailbox.release(guidance)
            if drain_task and not drain_task.done():
                drain_task.cancel()
            cancel_task.cancel()
            if process.returncode is None:
                await self._stop_current(interrupt=False)
            if stream_task and not stream_task.done():
                stream_task.cancel()
            await asyncio.gather(
                *(task for task in (drain_task, stream_task, cancel_task) if task is not None),
                return_exceptions=True,
            )
            if self.stderr_task:
                await asyncio.gather(self.stderr_task, return_exceptions=True)
            self.process = None
            self.pid = -1

    async def _stop_current(self, *, interrupt: bool) -> None:
        process = self.process
        if process is None or process.returncode is not None:
            return

        def send(sig: signal.Signals) -> None:
            try:
                if os.name == "posix" and process.pid > 1:
                    os.killpg(process.pid, sig)
                else:
                    process.send_signal(sig)
            except (ProcessLookupError, PermissionError, OSError):
                pass

        if interrupt:
            send(signal.SIGINT)
            try:
                await asyncio.wait_for(process.wait(), timeout=2)
                return
            except TimeoutError:
                pass
        send(signal.SIGTERM)
        try:
            await asyncio.wait_for(process.wait(), timeout=3)
            return
        except TimeoutError:
            pass
        send(signal.SIGKILL)
        try:
            await asyncio.wait_for(process.wait(), timeout=3)
        except TimeoutError as exc:
            raise WorkerRefusal("process_cleanup_failed", "Claude 하위 프로세스를 정리하지 못했습니다.") from exc

